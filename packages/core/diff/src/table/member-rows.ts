import type { DiffKind } from "./rows.js";

// The row of every member of every IR definition (requirement: an IR member with no row fails the coverage test).
// The walk reads it for the members it has no comparison of its own for: an `annotation` or `name` member reports
// an informative change, a fixed `{ kind, case }` row reports that case, any other row with no comparison reports
// `unclassified`. A member of a definition held whole by its parent (a deprecation's successor, a template, a
// value source) takes the parent member's row.

/** A member whose every change is one case of one row. */
export interface FixedMemberRow {
  readonly kind: DiffKind;
  readonly case: string;
}

export type MemberRow = DiffKind | FixedMemberRow;

type MemberRows = Readonly<Record<string, MemberRow>>;

const ANNOTATION_ONLY = "annotation";
const UNCLASSIFIED = "unclassified";

function fixed(kind: DiffKind, caseName: string): FixedMemberRow {
  return { kind, case: caseName };
}

// Every member of a definition held whole by its parent, on one row or one fixed case.
function wholeMembers(row: MemberRow, ...members: string[]): MemberRows {
  return Object.fromEntries(members.map((member) => [member, row]));
}

