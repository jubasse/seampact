package io.github.jubasse.seampact.springboot.runtime;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.example.tasks.api.TasksUnexpectedErrorListener;
import com.example.tasks.api.spring.TasksContractTable;
import com.example.tasks.api.spring.TasksSeampactBinding;
import com.example.tasksservice.api.TasksServiceUnexpectedErrorListener;
import com.example.tasksservice.api.spring.TasksServiceContractTable;
import com.example.tasksservice.api.spring.TasksServiceSeampactBinding;
import io.github.jubasse.seampact.hooks.AuthenticateResult;
import io.github.jubasse.seampact.hooks.OperationRef;
import io.github.jubasse.seampact.hooks.RequestView;
import io.github.jubasse.seampact.hooks.SignedTemplateRequest;
import java.lang.annotation.Annotation;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.ListableBeanFactory;
import org.springframework.beans.factory.support.StaticListableBeanFactory;
import org.springframework.core.env.StandardEnvironment;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * Two golden apis on the one shared runtime (ADR 0025): each boundary reaches only its own api's hook beans, a hook
 * bean of the runtime's own type stops the boot, and code generated by another version stops it before anything else.
 */
class SharedRuntimeTest {
    private static final String FAILURE_REASON = "handler threw";

    private final List<String> tasksFailures = new ArrayList<>();
    private final List<String> tasksServiceFailures = new ArrayList<>();

    @Test
    void eachApiReportsItsFailuresToItsOwnListenerOnly() {
        StaticListableBeanFactory beans = new StaticListableBeanFactory();
        TasksUnexpectedErrorListener tasksListener = failure -> tasksFailures.add(failure.api());
        TasksServiceUnexpectedErrorListener tasksServiceListener = failure -> tasksServiceFailures.add(failure.api());
        beans.addBean("tasksFailures", tasksListener);
        beans.addBean("tasksServiceFailures", tasksServiceListener);

        tasksBoundary(beans).report(Optional.empty(), FAILURE_REASON, new IllegalStateException(FAILURE_REASON));
        tasksServiceBoundary(beans).report(Optional.empty(), FAILURE_REASON, new IllegalStateException(FAILURE_REASON));

        assertEquals(List.of("tasks"), tasksFailures);
        assertEquals(List.of("tasksService"), tasksServiceFailures);
    }

    @Test
    void aHookBeanOfTheRuntimeTypeItselfStopsTheBoot() {
        StaticListableBeanFactory beans = new StaticListableBeanFactory();
        UnexpectedErrorListener unkeyed = failure -> { };
        beans.addBean("unkeyedFailures", unkeyed);

        IllegalStateException refused = assertThrows(IllegalStateException.class, () -> new BootCheck(tasksBoundary(beans)).afterSingletonsInstantiated());

        assertTrue(refused.getMessage().contains("the bean 'unkeyedFailures' implements UnexpectedErrorListener itself, which no api calls; fix: implement"
                + " the interface its api generates, TasksUnexpectedErrorListener for the api 'tasks'."), refused.getMessage());
    }

    @Test
    void codeGeneratedByAnotherVersionStopsTheBootBeforeAnyOtherCheck() {
        String otherVersion = "999.0.0";
        SeampactBoundary boundary = new SeampactBoundary(
                TasksContractTable.json(), new GeneratedBy(new TasksSeampactBinding(), otherVersion), new StaticListableBeanFactory(), new StandardEnvironment());

        IllegalStateException refused = assertThrows(IllegalStateException.class, () -> new BootCheck(boundary).afterSingletonsInstantiated());

        assertEquals("seampact: the api 'tasks' cannot start:\n- runtime.generated-for-other-version: The `tasks` boundary was generated by seampact `"
                + otherVersion + "`; the installed runtime is `" + SeampactRuntimeVersion.VERSION + "`; fix: run the seampact generate task again (Gradle"
                + " `seampactGenerate`, Maven `seampact:generate`) with the plugin at `" + SeampactRuntimeVersion.VERSION
                + "`, or install seampact-spring-runtime at `" + otherVersion + "` or a later patch of it.", refused.getMessage());
        assertFalse(refused.getMessage().contains("Spring MVC"));
    }

    private static SeampactBoundary tasksBoundary(ListableBeanFactory beans) {
        return new SeampactBoundary(TasksContractTable.json(), new TasksSeampactBinding(), beans, new StandardEnvironment());
    }

    private static SeampactBoundary tasksServiceBoundary(ListableBeanFactory beans) {
        return new SeampactBoundary(TasksServiceContractTable.json(), new TasksServiceSeampactBinding(), beans, new StandardEnvironment());
    }

    /** The golden binding as a generator of [generatorVersion] would have written it. */
    private record GeneratedBy(ApiBinding binding, String generatorVersion) implements ApiBinding {
        @Override
        public Map<String, Class<?>> inputTypes() {
            return binding.inputTypes();
        }

        @Override
        public Map<String, Class<? extends Annotation>> annotations() {
            return binding.annotations();
        }

        @Override
        public Map<Class<?>, Integer> successArms() {
            return binding.successArms();
        }

        @Override
        public Map<Class<?>, String> errorArms() {
            return binding.errorArms();
        }

        @Override
        public Optional<String> contractCode(Throwable exception) {
            return binding.contractCode(exception);
        }

        @Override
        public Map<String, Class<?>> authenticateHooks() {
            return binding.authenticateHooks();
        }

        @Override
        public Class<? extends Decider> deciderType() {
            return binding.deciderType();
        }

        @Override
        public Class<? extends ScopeResolver> scopeResolverType() {
            return binding.scopeResolverType();
        }

        @Override
        public Class<? extends UnexpectedErrorListener> unexpectedErrorListenerType() {
            return binding.unexpectedErrorListenerType();
        }

        @Override
        public AuthenticateResult<?, Denial> authenticate(String identity, ListableBeanFactory beans, JsonMapper mapper, JsonNode credentials,
                Optional<String> csrfToken, Optional<SignedTemplateRequest> signature, RequestView request, OperationRef operation) {
            return binding.authenticate(identity, beans, mapper, credentials, csrfToken, signature, request, operation);
        }
    }
}
