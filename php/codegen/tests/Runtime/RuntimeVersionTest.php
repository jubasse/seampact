<?php

declare(strict_types=1);

namespace Seampact\Codegen\Tests\Runtime;

use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Seampact\Codegen\Runtime\ApiContract;
use Seampact\Codegen\Runtime\RuntimeVersion;

/** The boot refuses a boundary generated for another runtime version (ADR 0025 "Version guards", G3). */
final class RuntimeVersionTest extends TestCase
{
    public function testTheBootRefusesAContractOfAnotherVersionBeforeAnyOtherCheck(): void
    {
        $this->expectException(\LogicException::class);
        $this->expectExceptionMessage("seampact runtime.generated-for-other-version: The 'tasks' boundary was generated by seampact 9.9.0; the installed runtime is " . RuntimeVersion::VERSION . '.');
        ApiContract::of(ForeignVersionContract::class);
    }

    public function testTheBootLoadsAContractOfItsOwnVersion(): void
    {
        self::assertSame('tasks', ApiContract::of(SelectionContract::class)->api);
    }

    /** @return iterable<string, array{string, string}> */
    public static function refusedPairs(): iterable
    {
        yield 'another minor' => ['1.2.0', '1.3.0'];
        yield 'another major' => ['1.2.0', '2.2.0'];
        yield 'a lower patch' => ['1.2.3', '1.2.2'];
        yield 'the development version against a released one' => ['0.0.0-dev', '0.0.0'];
        yield 'a released version against the development one' => ['0.0.0', '0.0.0-dev'];
        yield 'a version that is not semver' => ['dev-main', '1.2.0'];
    }

    #[DataProvider('refusedPairs')]
    public function testARuntimeOfAnotherMinorOrALowerPatchIsRefused(string $generatedBy, string $installed): void
    {
        $this->expectException(\LogicException::class);
        $this->expectExceptionMessage("install the runtime at {$generatedBy} or a later patch of it");
        RuntimeVersion::refuseOtherVersion('tasks', $generatedBy, $installed);
    }

    public function testARuntimePatchAtOrAboveTheGeneratorsPasses(): void
    {
        RuntimeVersion::refuseOtherVersion('tasks', '1.2.3', '1.2.3');
        RuntimeVersion::refuseOtherVersion('tasks', '1.2.3', '1.2.9');
        RuntimeVersion::refuseOtherVersion('tasks', RuntimeVersion::VERSION);
        $this->addToAssertionCount(3);
    }
}
