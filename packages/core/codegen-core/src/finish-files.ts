import type { Refusal } from "./refusal.js";
import type { FormatterParser, GeneratedFile, SourceFormat } from "./target.js";

interface FileKind {
  parser: FormatterParser;
  // Whether the header goes in as a `//` comment; JSON has no comment syntax, the manifest covers it.
  hasLineComments: boolean;
}

const FILE_KIND_BY_EXTENSION: Readonly<Record<string, FileKind>> = {
  ".ts": { parser: "typescript", hasLineComments: true },
  ".tsx": { parser: "typescript", hasLineComments: true },
  ".js": { parser: "babel", hasLineComments: true },
  ".mjs": { parser: "babel", hasLineComments: true },
  ".cjs": { parser: "babel", hasLineComments: true },
  ".json": { parser: "json", hasLineComments: false },
};

export interface HeaderSource {
  packageName: string;
  packageVersion: string;
  apiId: string;
}

// The one line every generated file with comment syntax starts with (ADR 0015 "The generated header").
export function generatedHeader(source: HeaderSource): string {
  return `Generated by ${source.packageName} ${source.packageVersion} from api "${source.apiId}". Do not edit.`;
}

// Adds the header and formats each file with the target's own Prettier `format`, its defaults and the parser its
// extension selects. A file of another extension, or one Prettier cannot parse, is refused by name.
export async function finishFiles(
  files: readonly GeneratedFile[],
  header: HeaderSource,
  format: SourceFormat,
): Promise<
  { status: "finished"; files: GeneratedFile[] } | { status: "refused"; refusals: Refusal[] }
> {
  const finished: GeneratedFile[] = [];
  const refusals: Refusal[] = [];

  for (const file of files) {
    const outcome = await finishFile(file, generatedHeader(header), format);

    if ("code" in outcome) refusals.push(outcome);
    else finished.push(outcome);
  }

  return refusals.length > 0
    ? { status: "refused", refusals }
    : { status: "finished", files: finished };
}

async function finishFile(
  file: GeneratedFile,
  headerLine: string,
  format: SourceFormat,
): Promise<GeneratedFile | Refusal> {
  const kind = fileKindOf(file.path);

  if (kind === undefined) {
    const known = Object.keys(FILE_KIND_BY_EXTENSION).join(", ");

    return {
      code: "file.extension.unsupported",
      message: `The target generated '${file.path}', whose extension is not one codegen-core formats (${known}).`,
      fix: "Report this to the target's maintainers: codegen-core must learn the extension before a target emits it.",
    };
  }

  const source = kind.hasLineComments ? `// ${headerLine}\n${file.contents}` : file.contents;

  try {
    return { path: file.path, contents: await format(source, { parser: kind.parser }) };
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);

    return {
      code: "file.format.failed",
      message: `Prettier could not format '${file.path}': ${reason}`,
      fix: "Report this to the target's maintainers: the target generated source its parser rejects.",
    };
  }
}

function fileKindOf(path: string): FileKind | undefined {
  const fileName = path.slice(path.lastIndexOf("/") + 1);
  const dot = fileName.lastIndexOf(".");

  if (dot <= 0) return undefined;

  const extension = fileName.slice(dot);

  return Object.hasOwn(FILE_KIND_BY_EXTENSION, extension)
    ? FILE_KIND_BY_EXTENSION[extension]
    : undefined;
}
