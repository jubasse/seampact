package io.github.jubasse.seampact.ir.write

import java.nio.file.Files
import java.nio.file.Path
import java.security.MessageDigest
import java.util.HexFormat
import kotlin.test.assertEquals
import kotlin.test.assertIs
import kotlin.test.assertTrue
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir

// The generated-file writer (ADR 0015 "Writing files" and "The generated header"), with the Node writer's codes.
class GeneratedWriterTest {
    @TempDir
    lateinit var workspace: Path

    private val out: Path get() = workspace.resolve("out")
    private val header = HeaderSource("io.github.jubasse:seampact-spring-boot", "0.1.0", "tasks")

    @Test
    fun addsTheHeaderToJavaFilesAndRefusesAnUnknownExtension() {
        val finished = assertIs<HeaderOutcome.Finished>(
            withGeneratedHeader(listOf(GeneratedFile("a/A.java", "class A {}\n"), GeneratedFile("b.json", "{}\n")), header),
        )
        assertEquals(
            "// Generated by io.github.jubasse:seampact-spring-boot 0.1.0 from api \"tasks\". Do not edit.\nclass A {}\n",
            finished.files[0].contents,
        )
        assertEquals("{}\n", finished.files[1].contents)

        val refused = assertIs<HeaderOutcome.Refused>(withGeneratedHeader(listOf(GeneratedFile("a.xml", "")), header))
        assertEquals(listOf("file.extension.unsupported"), refused.refusals.map { it.code })
    }

    @Test
    fun writesNormalizedFilesAndTheNodeWritersManifest() {
        write(GeneratedFile("b/B.java", "﻿class B {}\r\n"), GeneratedFile("A.java", "class A {}"))

        assertEquals("class B {}\n", Files.readString(out.resolve("b/B.java")))
        assertEquals("class A {}\n", Files.readString(out.resolve("A.java")))
        assertEquals(
            """
            {
              "owner": "server",
              "files": [
                {
                  "path": "A.java",
                  "sha256": "${sha256("class A {}\n")}"
                },
                {
                  "path": "b/B.java",
                  "sha256": "${sha256("class B {}\n")}"
                }
              ]
            }

            """.trimIndent(),
            Files.readString(out.resolve(MANIFEST_FILE_NAME)),
        )
    }

    @Test
    fun keepsUnchangedFilesAndRemovesStaleOnes() {
        write(GeneratedFile("A.java", "class A {}\n"), GeneratedFile("old/B.java", "class B {}\n"))

        val second = assertIs<PlanOutcome.Planned>(GeneratedWriter.plan(out, "server", listOf(GeneratedFile("A.java", "class A {}\n")), HandEditPolicy.REFUSE))
        val written = GeneratedWriter.commit(second.write)

        assertEquals(WrittenFiles(emptyList(), listOf("A.java"), listOf("old/B.java")), written)
        assertTrue(Files.notExists(out.resolve("old")))
    }

    @Test
    fun refusesAHandEditUnlessAskedToOverwrite() {
        write(GeneratedFile("A.java", "class A {}\n"))
        Files.writeString(out.resolve("A.java"), "class A { int edited; }\n")

        assertEquals(listOf("writer.file.edited"), refusedCodes(GeneratedFile("A.java", "class A {}\n")))
        assertIs<PlanOutcome.Planned>(GeneratedWriter.write(out, "server", listOf(GeneratedFile("A.java", "class A {}\n")), HandEditPolicy.OVERWRITE))
        assertEquals("class A {}\n", Files.readString(out.resolve("A.java")))
    }

    @Test
    fun refusesFilesItDidNotGenerateAndAnotherOwnersDirectory() {
        Files.createDirectories(out)
        Files.writeString(out.resolve("A.java"), "hand written\n")
        assertEquals(listOf("writer.file.not-generated"), refusedCodes(GeneratedFile("A.java", "class A {}\n")))

        Files.delete(out.resolve("A.java"))
        write(GeneratedFile("A.java", "class A {}\n"))
        val other = assertIs<PlanOutcome.Refused>(GeneratedWriter.plan(out, "client", listOf(GeneratedFile("A.java", "")), HandEditPolicy.REFUSE))
        assertEquals(listOf("writer.manifest.other-owner"), other.refusals.map { it.code })

        Files.writeString(out.resolve(MANIFEST_FILE_NAME), "not json")
        assertEquals(listOf("writer.manifest.invalid"), refusedCodes(GeneratedFile("A.java", "")))
    }

    @Test
    fun refusesPathsThatLeaveTheOutputDirectory() {
        assertEquals(listOf("file.path.invalid"), refusedCodes(GeneratedFile("../A.java", "")))
        assertEquals(listOf("file.path.invalid"), refusedCodes(GeneratedFile(MANIFEST_FILE_NAME, "")))
        assertEquals(listOf("file.path.invalid"), refusedCodes(GeneratedFile("A.java", ""), GeneratedFile("A.java", "")))

        Files.createDirectories(out)
        val elsewhere = Files.createDirectories(workspace.resolve("elsewhere"))
        Files.createSymbolicLink(out.resolve("linked"), elsewhere)
        assertEquals(listOf("writer.path.outside"), refusedCodes(GeneratedFile("linked/A.java", "")))
    }

    private fun write(vararg files: GeneratedFile) {
        assertIs<PlanOutcome.Planned>(GeneratedWriter.write(out, "server", files.toList(), HandEditPolicy.REFUSE))
    }

    private fun refusedCodes(vararg files: GeneratedFile): List<String> =
        assertIs<PlanOutcome.Refused>(GeneratedWriter.plan(out, "server", files.toList(), HandEditPolicy.REFUSE)).refusals.map { it.code }

    private fun sha256(text: String): String =
        HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(text.toByteArray()))
}
