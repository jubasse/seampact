package io.github.jubasse.seampact.springboot.runtime;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.Optional;
import org.junit.jupiter.api.Test;

/** The boot check's version step (ADR 0025, G3): which generated code a runtime serves. */
class GeneratorVersionCheckTest {
    private static final String API = "tasks";

    @Test
    void servesCodeOfItsOwnVersionAndOfAnEarlierPatch() {
        assertEquals(Optional.empty(), GeneratorVersionCheck.problem(API, "1.4.2", "1.4.2"));
        assertEquals(Optional.empty(), GeneratorVersionCheck.problem(API, "1.4.0", "1.4.2"));
        assertEquals(Optional.empty(), GeneratorVersionCheck.problem(API, "1.5.0-rc.1", "1.5.0-rc.1"));
    }

    @Test
    void refusesCodeOfALaterPatchAnotherMinorOrAnotherMajor() {
        for (String generated : new String[] {"1.4.3", "1.3.0", "1.5.0", "2.4.2"}) {
            Optional<String> problem = GeneratorVersionCheck.problem(API, generated, "1.4.2");

            assertTrue(problem.isPresent(), generated);
            assertTrue(problem.get().startsWith(GeneratorVersionCheck.GENERATED_FOR_OTHER_VERSION + ": The `tasks` boundary was generated by seampact `"
                    + generated + "`; the installed runtime is `1.4.2`"), problem.get());
        }
    }

    @Test
    void refusesAPrereleaseAgainstAnyOtherVersion() {
        assertTrue(GeneratorVersionCheck.problem(API, "1.5.0-rc.1", "1.5.0").isPresent());
        assertTrue(GeneratorVersionCheck.problem(API, "1.5.0", "1.5.0-rc.1").isPresent());
    }
}
