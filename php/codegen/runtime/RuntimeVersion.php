<?php

declare(strict_types=1);

namespace Seampact\Codegen\Runtime;

/**
 * The version of the installed PHP runtime and of the generators shipped with it (one package, one version): the
 * generators stamp it into each contract class, and the boot refuses a contract stamped for another `major.minor`
 * or a higher patch. The release pipeline stamps the constant; unreleased, it holds the development version.
 */
final class RuntimeVersion
{
    public const VERSION = '0.0.0-dev';
    public const GENERATED_FOR_OTHER_VERSION = 'runtime.generated-for-other-version';
    private const PATTERN = '/^(\d+)\.(\d+)\.(\d+)(-[0-9A-Za-z.-]+)?$/';

    private function __construct()
    {
    }

    /** @throws \LogicException the contract was generated for another runtime, with the fix */
    public static function refuseOtherVersion(string $api, string $generatedBy, string $installed = self::VERSION): void
    {
        if (self::accepts($generatedBy, $installed)) {
            return;
        }

        throw new \LogicException(
            'seampact ' . self::GENERATED_FOR_OTHER_VERSION . ": The '{$api}' boundary was generated by seampact {$generatedBy}; the installed runtime is {$installed}."
            . " Run seampact generate again with the generator at {$installed}, or install the runtime at {$generatedBy} or a later patch of it.",
        );
    }

    /** The same `major.minor` and a patch at or above the generator's; a pre-release (the development version) matches only itself. */
    private static function accepts(string $generatedBy, string $installed): bool
    {
        if (preg_match(self::PATTERN, $generatedBy, $generated) !== 1 || preg_match(self::PATTERN, $installed, $runtime) !== 1) {
            return false;
        }

        if ($generated[1] !== $runtime[1] || $generated[2] !== $runtime[2]) {
            return false;
        }

        if ((int) $runtime[3] !== (int) $generated[3]) {
            return (int) $runtime[3] > (int) $generated[3] && !isset($runtime[4]) && !isset($generated[4]);
        }

        return ($generated[4] ?? '') === ($runtime[4] ?? '');
    }
}
