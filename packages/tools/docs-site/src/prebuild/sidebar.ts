import type { Link, List, ListItem, Root } from "mdast";
import { visit } from "unist-util-visit";
import { type LinkContext, resolveLinkTarget } from "./link-target.ts";
import { plainText } from "./markdown-tree.ts";
import { DOCS_INDEX_SLUG } from "./page-policy.ts";
import { SITE_BASE } from "./site-layout.ts";

const INDEX_DOCS_PATH = "README.md";
const OPEN_SECTION_LABEL = "Getting started";
const CONTRIBUTOR_SECTION_LABEL = "Design";
const CONTRIBUTOR_SECTION_SIDEBAR_LABEL = "Design (for contributors)";
const DOCS_INDEX_SIDEBAR_LABEL = "Documentation index";

/** A Starlight sidebar entry, as `starlight({ sidebar })` reads it. */
export type SidebarEntry =
  | { label: string; slug: string }
  | { label: string; link: string }
  | { autogenerate: { directory: string } }
  | { label: string; collapsed?: boolean; items: SidebarEntry[] };

/** One group of the docs index: a `##` section and the first link of each of its list items. */
interface IndexSection {
  label: string;
  links: { label: string; url: string; line: number }[];
}

/** The sidebar in the order docs/README.md gives: one group per section, one entry per listed page. */
export interface SiteSidebar {
  entries: SidebarEntry[];
  /** The slugs the sidebar links to, autogenerated folders included as `<folder>/`. */
  coveredSlugs: Set<string>;
  /** The title of each folder index the prebuild writes, from the index entry that names the folder. */
  folderTitles: Map<string, string>;
}

/**
 * Builds the sidebar from the docs index. A link to a page is a sidebar link; a link to a folder
 * with no README lists that folder's pages, so a reference folder needs no hand-kept list.
 */
export function buildSidebar(
  indexTree: Root,
  foldersWithoutReadme: ReadonlySet<string>,
  context: LinkContext,
): SiteSidebar {
  const coveredSlugs = new Set<string>();
  const folderTitles = new Map<string, string>();
  const entries: SidebarEntry[] = [{ label: DOCS_INDEX_SIDEBAR_LABEL, slug: DOCS_INDEX_SLUG }];

  coveredSlugs.add(DOCS_INDEX_SLUG);

  for (const section of readIndexSections(indexTree)) {
    const items = section.links
      .map((link) =>
        sidebarEntryFor(link, foldersWithoutReadme, context, coveredSlugs, folderTitles),
      )
      .filter((entry): entry is SidebarEntry => entry !== undefined);

    if (items.length > 0) entries.push(sectionEntry(section.label, items));

    const sectionFolder = commonFolder(items);

    if (sectionFolder !== undefined && !folderTitles.has(sectionFolder))
      folderTitles.set(sectionFolder, section.label);
  }

  return { entries, coveredSlugs, folderTitles };
}

/** Every group starts closed except the first steps; the contributor group says who it is for. */
function sectionEntry(label: string, items: SidebarEntry[]): SidebarEntry {
  return {
    label: label === CONTRIBUTOR_SECTION_LABEL ? CONTRIBUTOR_SECTION_SIDEBAR_LABEL : label,
    collapsed: label !== OPEN_SECTION_LABEL,
    items,
  };
}

function readIndexSections(indexTree: Root): IndexSection[] {
  const sections: IndexSection[] = [];

  for (const block of indexTree.children) {
    if (block.type === "heading" && block.depth === 2)
      sections.push({ label: plainText(block).trim(), links: [] });

    const currentSection = sections.at(-1);

    if (block.type !== "list") continue;

    if (currentSection === undefined) {
      throw new Error(
        `docs/${INDEX_DOCS_PATH}:${block.position?.start.line}: a list comes before the first "##" section, so it has no sidebar group. Put it under a section.`,
      );
    }

    currentSection.links.push(...firstLinkOfEachItem(block));
  }

  return sections;
}

function firstLinkOfEachItem(list: List): IndexSection["links"] {
  return list.children.map((item) => {
    const line = item.position?.start.line ?? 0;
    const firstLink = findFirstLink(item);

    if (firstLink === undefined)
      throw new Error(`docs/${INDEX_DOCS_PATH}:${line}: an index entry has no link to a page.`);

    return { label: plainText(firstLink).trim(), url: firstLink.url, line };
  });
}

function findFirstLink(item: ListItem): Link | undefined {
  const links: Link[] = [];

  visit(item, "link", (link) => {
    links.push(link);
  });

  return links[0];
}

function sidebarEntryFor(
  link: IndexSection["links"][number],
  foldersWithoutReadme: ReadonlySet<string>,
  context: LinkContext,
  coveredSlugs: Set<string>,
  folderTitles: Map<string, string>,
): SidebarEntry | undefined {
  const target = resolveLinkTarget(link.url, INDEX_DOCS_PATH, context);

  if (target.kind === "broken")
    throw new Error(`docs/${INDEX_DOCS_PATH}:${link.line}: ${target.reason}.`);

  if (target.kind === "unchanged" || !target.url.startsWith(SITE_BASE)) {
    return { label: link.label, link: target.kind === "unchanged" ? link.url : target.url };
  }

  const slug = target.url.slice(SITE_BASE.length).replace(/#.*$/, "").replace(/\/$/, "");

  if (foldersWithoutReadme.has(slug)) {
    coveredSlugs.add(`${slug}/`);
    folderTitles.set(slug, link.label);

    return { label: link.label, collapsed: true, items: [{ autogenerate: { directory: slug } }] };
  }

  // A page the index lists twice (or reaches through a moved page) stays where it came first.
  if (coveredSlugs.has(slug)) return undefined;

  coveredSlugs.add(slug);

  return { label: link.label, slug };
}

function commonFolder(items: SidebarEntry[]): string | undefined {
  const folders = new Set(
    items.map((item) =>
      "slug" in item && item.slug.includes("/") ? item.slug.split("/")[0] : undefined,
    ),
  );

  if (folders.size !== 1) return undefined;

  return [...folders][0];
}
