import type { DiffKind } from "./rows.js";

// The row of every member of every IR definition (requirement: an IR member with no row fails the coverage test).
// The walk reads it for the members it has no comparison of its own for: an `annotation` or `name` member reports
// an informative change, any other row with no comparison reports `unclassified`. A member of a definition held
// whole by its parent (a deprecation's successor, a template) takes the parent member's row. The access, rights,
// errors, headers, paging, idempotency and concurrency members are `unclassified` until their rows land.

type MemberRows = Readonly<Record<string, DiffKind>>;

const ANNOTATION_ONLY = "annotation";
const UNCLASSIFIED = "unclassified";

// A definition compared whole by a member with no row yet: every member `unclassified`.
function unclassifiedMembers(...members: string[]): MemberRows {
  return Object.fromEntries(members.map((member) => [member, UNCLASSIFIED]));
}

