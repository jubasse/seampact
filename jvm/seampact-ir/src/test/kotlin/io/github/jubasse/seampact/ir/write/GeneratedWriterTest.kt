package io.github.jubasse.seampact.ir.write

import java.nio.file.Files
import java.nio.file.Path
import java.security.MessageDigest
import java.util.HexFormat
import kotlin.io.path.readText
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertIs
import kotlin.test.assertTrue
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir

// The generated-file writer (ADR 0015 "Writing files" and "The generated header"), with the Node writer's codes.
class GeneratedWriterTest {
    @TempDir
    lateinit var workspace: Path

    private val out: Path get() = workspace.resolve("out")
    private val header = HeaderSource("io.github.jubasse:seampact-spring-boot", "0.1.0", "tasks")

    @Test
    fun addsTheHeaderToJavaAndPropertiesFilesAndRefusesAnUnknownExtension() {
        val finished = assertIs<HeaderOutcome.Finished>(
            withGeneratedHeader(listOf(GeneratedFile("a/A.java", "class A {}\n"), GeneratedFile("b.json", "{}\n")), header),
        )
        assertEquals(
            "// Generated by io.github.jubasse:seampact-spring-boot 0.1.0 from api \"tasks\". Do not edit.\nclass A {}\n",
            finished.files[0].contents,
        )
        assertEquals("{}\n", finished.files[1].contents)

        val properties = assertIs<HeaderOutcome.Finished>(withGeneratedHeader(listOf(GeneratedFile("seampact-tasks.properties", "a=b\n")), header))
        assertEquals(
            "# Generated by io.github.jubasse:seampact-spring-boot 0.1.0 from api \"tasks\". Do not edit.\na=b\n",
            properties.files.single().contents,
        )

        val refused = assertIs<HeaderOutcome.Refused>(withGeneratedHeader(listOf(GeneratedFile("a.xml", "")), header))
        assertEquals(listOf("file.extension.unsupported"), refused.refusals.map { it.code })
    }

    @Test
    fun writesNormalizedFilesAndTheNodeWritersManifest() {
        write(GeneratedFile("b/B.java", "﻿class B {}\r\n"), GeneratedFile("A.java", "class A {}"))

        assertEquals("class B {}\n", Files.readString(out.resolve("b/B.java")))
        assertEquals("class A {}\n", Files.readString(out.resolve("A.java")))
        assertEquals(
            """
            {
              "owner": "server",
              "files": [
                {
                  "path": "A.java",
                  "sha256": "${sha256("class A {}\n")}"
                },
                {
                  "path": "b/B.java",
                  "sha256": "${sha256("class B {}\n")}"
                }
              ]
            }

            """.trimIndent(),
            Files.readString(out.resolve(MANIFEST_FILE_NAME)),
        )
    }

    @Test
    fun keepsUnchangedFilesAndRemovesStaleOnes() {
        write(GeneratedFile("A.java", "class A {}\n"), GeneratedFile("old/B.java", "class B {}\n"))

        val second = assertIs<PlanOutcome.Planned>(GeneratedWriter.plan(out, "server", listOf(GeneratedFile("A.java", "class A {}\n")), HandEditPolicy.REFUSE))
        val written = GeneratedWriter.commit(second.write)

        assertEquals(WrittenFiles(emptyList(), listOf("A.java"), listOf("old/B.java")), written)
        assertTrue(Files.notExists(out.resolve("old")))
    }

    @Test
    fun refusesAHandEditUnlessAskedToOverwrite() {
        write(GeneratedFile("A.java", "class A {}\n"))
        Files.writeString(out.resolve("A.java"), "class A { int edited; }\n")

        assertEquals(listOf("writer.file.edited"), refusedCodes(GeneratedFile("A.java", "class A {}\n")))
        assertIs<PlanOutcome.Planned>(GeneratedWriter.write(out, "server", listOf(GeneratedFile("A.java", "class A {}\n")), HandEditPolicy.OVERWRITE))
        assertEquals("class A {}\n", Files.readString(out.resolve("A.java")))
    }

    @Test
    fun refusesFilesItDidNotGenerateAndAnotherOwnersDirectory() {
        Files.createDirectories(out)
        Files.writeString(out.resolve("A.java"), "hand written\n")
        assertEquals(listOf("writer.file.not-generated"), refusedCodes(GeneratedFile("A.java", "class A {}\n")))

        Files.delete(out.resolve("A.java"))
        write(GeneratedFile("A.java", "class A {}\n"))
        val other = assertIs<PlanOutcome.Refused>(GeneratedWriter.plan(out, "client", listOf(GeneratedFile("A.java", "")), HandEditPolicy.REFUSE))
        assertEquals(listOf("writer.manifest.other-owner"), other.refusals.map { it.code })

        Files.writeString(out.resolve(MANIFEST_FILE_NAME), "not json")
        assertEquals(listOf("writer.manifest.invalid"), refusedCodes(GeneratedFile("A.java", "")))
    }

    @Test
    fun refusesTwoPathsThatDifferOnlyByCase() {
        for ((first, second) in listOf("Tasks.java" to "tasks.java", "routes/É.java" to "routes/é.java")) {
            val refused = assertIs<PlanOutcome.Refused>(
                GeneratedWriter.plan(out, "server", listOf(GeneratedFile(first, ""), GeneratedFile(second, "")), HandEditPolicy.REFUSE),
            )

            assertEquals(listOf("file.path.invalid"), refused.refusals.map { it.code })
            assertTrue("'$second', and it differs only by letter case from '$first'" in refused.refusals[0].message)
        }

        assertFalse(Files.exists(out))
    }

    @Test
    fun theCaseFoldAgreesWithTheSharedVectorPairs() {
        val vectors = Path.of(System.getProperty("seampact.repositoryRoot"), "packages/core/spec/vectors/generated-paths/case-fold.json")

        for (pair in Json.parseToJsonElement(vectors.readText()).jsonObject.getValue("pairs").jsonArray) {
            val first = pair.jsonObject.getValue("first").jsonPrimitive.content
            val second = pair.jsonObject.getValue("second").jsonPrimitive.content
            val collide = pair.jsonObject.getValue("collide").jsonPrimitive.boolean

            assertEquals(collide, refusalMessagesOfPaths(first, second).isNotEmpty(), "$first and $second")
        }
    }

    @Test
    fun refusesDirectoriesThatDifferOnlyByCaseAndAFileThatIsAlsoADirectory() {
        val cases = listOf(
            listOf("Routes/a.java", "routes/b.java"),
            listOf("routes/b.java", "Routes/a.java"),
            listOf("routes", "Routes/a.java"),
            listOf("Routes/a.java", "routes"),
            listOf("routes", "routes/a.java"),
        )

        for (paths in cases) assertEquals(1, refusalMessagesOfPaths(*paths.toTypedArray()).size, paths.toString())

        assertTrue("differs only by letter case from the directory 'Routes'" in refusalMessagesOfPaths(*cases[0].toTypedArray())[0])
    }

    @Test
    fun reportsAPathRepeatedAfterACaseVariantAsGeneratedTwice() {
        val messages = refusalMessagesOfPaths("a.java", "A.java", "A.java")

        assertEquals(2, messages.size)
        assertTrue("differs only by letter case from 'a.java'" in messages[0])
        assertTrue("it is generated twice" in messages[1])
    }

    @Test
    fun givesAStaleFileRenamedOnlyByCaseItsOwnMessageAndFix() {
        write(GeneratedFile("Tasks.java", "class A {}\n"))
        // What a case-insensitive disk shows: the new spelling already exists.
        Files.writeString(out.resolve("tasks.java"), "class A {}\n")

        val refused = assertIs<PlanOutcome.Refused>(
            GeneratedWriter.plan(out, "server", listOf(GeneratedFile("tasks.java", "class A {}\n")), HandEditPolicy.REFUSE),
        )

        assertEquals(listOf("writer.file.not-generated"), refused.refusals.map { it.code })
        assertTrue("only by letter case" in refused.refusals[0].message)
        assertFalse("did not generate it" in refused.refusals[0].message)
        assertTrue("Delete" in refused.refusals[0].fix)
    }

    private fun refusalMessagesOfPaths(vararg paths: String): List<String> =
        checkGeneratedPaths(paths.map { GeneratedFile(it, "") }).second.map { it.message }

    @Test
    fun refusesPathsThatLeaveTheOutputDirectory() {
        assertEquals(listOf("file.path.invalid"), refusedCodes(GeneratedFile("../A.java", "")))
        assertEquals(listOf("file.path.invalid"), refusedCodes(GeneratedFile(MANIFEST_FILE_NAME, "")))
        assertEquals(listOf("file.path.invalid"), refusedCodes(GeneratedFile("A.java", ""), GeneratedFile("A.java", "")))

        Files.createDirectories(out)
        val elsewhere = Files.createDirectories(workspace.resolve("elsewhere"))
        Files.createSymbolicLink(out.resolve("linked"), elsewhere)
        assertEquals(listOf("writer.path.outside"), refusedCodes(GeneratedFile("linked/A.java", "")))
    }

    @Test
    fun refusesALinkInPlaceOfAGeneratedFileOrOfTheManifest() {
        write(GeneratedFile("A.java", "class A {}\n"))
        val target = Files.writeString(workspace.resolve("target.java"), "class A {}\n")

        Files.delete(out.resolve("A.java"))
        Files.createSymbolicLink(out.resolve("A.java"), target)
        assertEquals(listOf("writer.file.not-generated"), refusedCodes(GeneratedFile("A.java", "class A {}\n")))

        Files.delete(out.resolve("A.java"))
        val manifest = Files.move(out.resolve(MANIFEST_FILE_NAME), workspace.resolve("manifest.json"))
        Files.createSymbolicLink(out.resolve(MANIFEST_FILE_NAME), manifest)
        assertEquals(listOf("writer.manifest.not-regular"), refusedCodes(GeneratedFile("A.java", "class A {}\n")))
    }

    private fun write(vararg files: GeneratedFile) {
        assertIs<PlanOutcome.Planned>(GeneratedWriter.write(out, "server", files.toList(), HandEditPolicy.REFUSE))
    }

    private fun refusedCodes(vararg files: GeneratedFile): List<String> =
        assertIs<PlanOutcome.Refused>(GeneratedWriter.plan(out, "server", files.toList(), HandEditPolicy.REFUSE)).refusals.map { it.code }

    private fun sha256(text: String): String =
        HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(text.toByteArray()))
}
