<?php

declare(strict_types=1);

namespace Seampact\Laravel\Tests;

use PHPUnit\Framework\TestCase;
use Seampact\Codegen\Tests\Support\ReferenceContract;
use Seampact\Ir\Run\GenerationRefusedException;
use Seampact\Laravel\LaravelGenerator;

/** A page fact 1.0 does not generate is refused by name: the reference's changes feed, whose page carries `complete`. */
final class PageFactRefusalTest extends TestCase
{
    private const PAGING_IR = 'tasksPaging.ir.json';

    public function testTheCompletePageFactOfAChangesFeedIsRefusedByName(): void
    {
        $generator = new LaravelGenerator();

        try {
            $generator->generate(ReferenceContract::read($generator, ReferenceContract::document(self::PAGING_IR)), ReferenceContract::entry(LaravelGenerator::PACKAGE, 'tasksPaging', 'App\\TasksPaging'));
            self::fail('The changes feed was generated, but its complete page fact should be refused.');
        } catch (GenerationRefusedException $refused) {
            $refusedFacts = [];
            foreach ($refused->problems as $problem) {
                if ($problem->code === 'paging.handlerResult.unsupported') {
                    $refusedFacts[] = $problem->message;
                }
            }

            self::assertCount(2, $refusedFacts);
            self::assertSame("The page fact 'complete' is not generated by the laravel target yet: the 1.0 PHP targets do not serve it, so it comes after 1.0.", $refusedFacts[0]);
        }
    }
}
