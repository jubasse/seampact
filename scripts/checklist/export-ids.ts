// Writes docs/conformance/ids.yaml from the FEAT-001 framing (prd.yaml and scenarios.yaml):
// every FR id with its name and every scenario id with its title, sorted, nothing else.
// The framing is git-ignored; the lead regenerates the file when FEAT-001 changes.
//   node scripts/checklist/export-ids.ts --favir <FEAT-001 directory> [--out <file>] [--check]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { parse } from "yaml";

/**
 * Terms that must never reach the committed export (private project names). They are never
 * written in a tracked file: they come from the SEAMPACT_PRIVATE_TERMS environment variable
 * (comma or newline separated) or from the untracked file .favir/private-terms.txt (one per line).
 */
export function privateTerms(
  env: NodeJS.ProcessEnv = process.env,
  root: string = resolve(dirname(fileURLToPath(import.meta.url)), "../.."),
): string[] {
  const file = join(root, ".favir", "private-terms.txt");
  const raw = [
    env.SEAMPACT_PRIVATE_TERMS ?? "",
    existsSync(file) ? readFileSync(file, "utf8") : "",
  ];

  return raw
    .join("\n")
    .split(/[,\n]/)
    .map((t) => t.trim().toLowerCase())
    .filter((t) => t !== "");
}

/** Titles that name a private project, rewritten neutrally. */
export const TITLE_OVERRIDES: Record<string, string> = {
  "SCN-024": "A test consumer project runs end to end at a large real-world scale",
};

const HEADER = "# Generated by scripts/checklist/export-ids.ts from FEAT-001. Do not edit.\n";

const byNumber = (a: string, b: string) => Number(a.split("-")[1]) - Number(b.split("-")[1]);

function collect(
  rows: unknown,
  field: "name" | "title",
  prefix: string,
  overrides: Record<string, string>,
): Record<string, string> {
  if (!Array.isArray(rows)) throw new Error(`expected a list of ${prefix} entries`);
  const out: Record<string, string> = {};

  for (const row of rows as Record<string, unknown>[]) {
    const id = row.id;

    if (typeof id !== "string" || !id.startsWith(`${prefix}-`)) continue;
    const text = overrides[id] ?? row[field];

    if (typeof text !== "string" || text.trim() === "") throw new Error(`${id}: missing ${field}`);
    out[id] = text.replace(/\s+/g, " ").trim();
  }

  return out;
}

export function buildIds(
  prd: unknown,
  scenarios: unknown,
  forbidden: readonly string[] = privateTerms(),
): string {
  const frs = collect((prd as { features?: unknown }).features, "name", "FR", {});
  const scns = collect(
    (scenarios as { scenarios?: unknown }).scenarios,
    "title",
    "SCN",
    TITLE_OVERRIDES,
  );
  const section = (name: string, rows: Record<string, string>) => [
    `${name}:`,
    ...Object.keys(rows)
      .sort(byNumber)
      .map((id) => `  ${id}: ${JSON.stringify(rows[id])}`),
  ];
  const text = `${HEADER}${[...section("frs", frs), ...section("scenarios", scns)].join("\n")}\n`;
  const lower = text.toLowerCase();

  if (forbidden.some((t) => lower.includes(t)))
    throw new Error("the export would contain a private term (SEAMPACT_PRIVATE_TERMS)");

  return text;
}

export function exportFromDir(favirDir: string): string {
  const read = (f: string) => parse(readFileSync(join(favirDir, f), "utf8")) as unknown;

  return buildIds(read("prd.yaml"), read("scenarios.yaml"));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({
    options: { favir: { type: "string" }, out: { type: "string" }, check: { type: "boolean" } },
  });

  if (!values.favir) {
    console.error("usage: export-ids.ts --favir <FEAT-001 directory> [--out <file>] [--check]");
    process.exit(2);
  }

  const out =
    values.out ??
    resolve(dirname(fileURLToPath(import.meta.url)), "../../docs/conformance/ids.yaml");
  const text = exportFromDir(values.favir);

  if (values.check) {
    const same = readFileSync(out, "utf8") === text;

    console.error(same ? "ids export: up to date" : `ids export: ${out} is stale`);
    process.exit(same ? 0 : 1);
  }

  writeFileSync(out, text);
  console.error(`ids export: wrote ${out}`);
}
