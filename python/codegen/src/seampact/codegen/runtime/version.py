"""The version of the installed runtime and of the generator shipped with it (ADR 0025 "Version guards", G3): the
generator stamps it into each api's code as `GENERATED_BY`, and the boot check, first of all, refuses code stamped for
another `major.minor` or a higher patch. The release pipeline stamps the constant; unreleased, it holds the
development version, which matches only itself."""

import re
from typing import Final

RUNTIME_VERSION: Final = "1.1.0"
GENERATED_FOR_OTHER_VERSION: Final = "runtime.generated-for-other-version"

_VERSION: Final = re.compile(r"(\d+)\.(\d+)\.(\d+)(-[0-9A-Za-z.-]+)?")


class RuntimeVersionError(RuntimeError):
    """The api's generated code was written for another runtime; the message names both versions and the fix."""

    code = GENERATED_FOR_OTHER_VERSION


def accepts(generated_by: str, installed: str = RUNTIME_VERSION) -> bool:
    """The same version, or the same `major.minor` with an installed patch at or above the generator's; a
    pre-release matches only itself."""
    if generated_by == installed:
        return True

    generated = _VERSION.fullmatch(generated_by)
    runtime = _VERSION.fullmatch(installed)

    if generated is None or runtime is None or generated.group(1, 2) != runtime.group(1, 2):
        return False

    generated_patch = int(generated.group(3))
    runtime_patch = int(runtime.group(3))

    if generated_patch != runtime_patch:
        return runtime_patch > generated_patch and generated.group(4) is None and runtime.group(4) is None

    return generated.group(4) == runtime.group(4)


def other_version_problem(api: str, generated_by: str, installed: str = RUNTIME_VERSION) -> str | None:
    """The boot check's first line, or None when the runtime accepts the generated code."""
    if accepts(generated_by, installed):
        return None

    return (
        f"seampact {GENERATED_FOR_OTHER_VERSION}: The '{api}' boundary was generated by seampact {generated_by}; "
        f"the installed runtime is {installed}. Run seampact generate again with the generator at {installed}, "
        f"or install the runtime at {generated_by} or a later patch of it."
    )


def refuse_other_version(api: str, generated_by: str, installed: str = RUNTIME_VERSION) -> None:
    """Raises `RuntimeVersionError` when the runtime does not accept the generated code."""
    problem = other_version_problem(api, generated_by, installed)

    if problem is not None:
        raise RuntimeVersionError(problem)
