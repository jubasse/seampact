//! The comparison of generated output: files as token streams with the header normalised, and
//! the Rust manifest checked against the bytes it lists.

use camino::Utf8Path;
use seampact_json::escape_pointer;
use serde_json::Value;

use crate::tool_compare::sha256_hex;
use crate::{Mismatch, MismatchKind};

/// The manifest every output directory of a generated write holds. Copied from the writer on
/// purpose: the oracle stays independent of the code under test.
pub const GENERATED_MANIFEST_FILE: &str = ".seampact-manifest.json";

/// The owner of the manifest of a directory of OpenAPI documents; a deliberate copy, as above.
pub const DOCUMENT_OWNER: &str = "openapi";

/// The manifest version the Rust writer writes.
const RUST_MANIFEST_VERSION: u64 = 2;

/// The extensions compared as token streams.
const TOKEN_COMPARED_EXTENSIONS: [&str; 6] = [".ts", ".tsx", ".js", ".mjs", ".cjs", ".json"];

/// The extensions where the two formatter rewrites are normalised.
const TYPESCRIPT_EXTENSIONS: [&str; 2] = [".ts", ".tsx"];

/// The comment that opens and closes a generated header; a deliberate copy of the writer's, as above.
const HEADER_PREFIX: &str = "// Generated by ";
const HEADER_API_MARK: &str = " from api \"";
const HEADER_SUFFIX: &str = "\". Do not edit.";

/// The tokens a union's leading `|` follows: it starts a type, so it is no operator.
const UNION_START_PREDECESSORS: [&str; 6] = ["=", ":", "(", "<", ",", "["];

/// Whether `path` is compared as a token stream once it is generated output.
#[must_use]
pub fn is_token_compared(path: &str) -> bool {
    TOKEN_COMPARED_EXTENSIONS
        .iter()
        .any(|extension| path.ends_with(extension))
}

/// The directory of a manifest path, `None` when `path` is no manifest.
#[must_use]
pub fn manifest_directory(path: &str) -> Option<&str> {
    if path == GENERATED_MANIFEST_FILE {
        return Some("");
    }

    path.strip_suffix(GENERATED_MANIFEST_FILE)?
        .strip_suffix('/')
}

/// The manifest directory, among `directories`, that holds `path`, the deepest first.
#[must_use]
pub fn holding_directory<'directory>(
    path: &str,
    directories: &[&'directory str],
) -> Option<&'directory str> {
    directories
        .iter()
        .copied()
        .filter(|directory| directory.is_empty() || path.starts_with(&format!("{directory}/")))
        .max_by_key(|directory| directory.len())
}

/// The one mismatch of a generated file whose token streams differ: its pointer is `/<path>`,
/// `expected` and `actual` the differing token text. `short_id_of` maps a TypeScript package name
/// to its short id.
#[must_use]
pub fn generated_file_mismatch(
    path: &str,
    expected_text: &str,
    actual_text: &str,
    short_id_of: &dyn Fn(&str) -> Option<String>,
) -> Option<Mismatch> {
    let expected_header = normalized_header(expected_text, short_id_of);
    let actual_header = normalized_header(actual_text, short_id_of);
    let expected_tokens = comparable_tokens(path, &expected_header);
    let actual_tokens = comparable_tokens(path, &actual_header);

    if expected_tokens == actual_tokens {
        return None;
    }

    let common_start = expected_tokens
        .iter()
        .zip(&actual_tokens)
        .take_while(|(expected, actual)| expected == actual)
        .count();
    let expected_rest = expected_tokens.get(common_start..).unwrap_or_default();
    let actual_rest = actual_tokens.get(common_start..).unwrap_or_default();
    let common_end = expected_rest
        .iter()
        .rev()
        .zip(actual_rest.iter().rev())
        .take_while(|(expected, actual)| expected == actual)
        .count();
    let differing = |tokens: &[&str]| {
        tokens
            .get(..tokens.len() - common_end)
            .unwrap_or_default()
            .join(" ")
    };

    Some(Mismatch {
        pointer: Some(generated_file_pointer(path)),
        kind: MismatchKind::Value,
        expected: Some(Value::String(differing(expected_rest))),
        actual: Some(Value::String(differing(actual_rest))),
    })
}

/// The pointer of the mismatch of a generated file.
#[must_use]
pub fn generated_file_pointer(path: &str) -> String {
    format!("/{}", escape_pointer(path))
}

/// The text with its first line, when it is a generated header, written as
/// `// Generated by <generator> (<short id>) from api "<api id>". Do not edit.`: the TypeScript
/// header names a package and its version, the Rust one seampact, its version and the short id.
fn normalized_header(text: &str, short_id_of: &dyn Fn(&str) -> Option<String>) -> String {
    let (first_line, rest) = text.split_once('\n').unwrap_or((text, ""));

    let Some((generator, api_id)) = first_line
        .strip_prefix(HEADER_PREFIX)
        .and_then(|header| header.strip_suffix(HEADER_SUFFIX))
        .and_then(|header| header.split_once(HEADER_API_MARK))
    else {
        return text.to_owned();
    };

    let short_id = rust_short_id(generator).map_or_else(
        || typescript_short_id(generator, short_id_of),
        str::to_owned,
    );

    format!(
        "{HEADER_PREFIX}<generator> ({short_id}){HEADER_API_MARK}{api_id}{HEADER_SUFFIX}\n{rest}"
    )
}

/// The short id of a Rust header's `seampact <version> (<short id>)`.
fn rust_short_id(generator: &str) -> Option<&str> {
    let (_, short_id) = generator.strip_prefix("seampact ")?.split_once(" (")?;

    short_id.strip_suffix(')')
}

/// The short id of a TypeScript header's `<package> <version>`; a package the registry does not
/// name keeps its name, as a probe's package name is its id.
fn typescript_short_id(generator: &str, short_id_of: &dyn Fn(&str) -> Option<String>) -> String {
    let package_name = generator
        .rsplit_once(' ')
        .map_or(generator, |(package_name, _)| package_name);

    short_id_of(package_name).unwrap_or_else(|| package_name.to_owned())
}

/// The tokens of a file, with the two TypeScript formatter rewrites undone in `.ts` and `.tsx`: a
/// `,` right before a closing `>`, and the leading `|` of a union.
fn comparable_tokens<'text>(path: &str, text: &'text str) -> Vec<&'text str> {
    let tokens = source_tokens(text);
    let is_typescript = TYPESCRIPT_EXTENSIONS
        .iter()
        .any(|extension| path.ends_with(extension));

    if !is_typescript {
        return tokens;
    }

    let mut kept: Vec<&str> = Vec::with_capacity(tokens.len());

    for (index, token) in tokens.iter().copied().enumerate() {
        let next = tokens.get(index + 1).copied();
        let is_trailing_comma = token == "," && next == Some(">");
        let is_leading_union_bar = token == "|"
            && kept
                .last()
                .is_some_and(|previous| UNION_START_PREDECESSORS.contains(previous));

        if !is_trailing_comma && !is_leading_union_bar {
            kept.push(token);
        }
    }

    kept
}

/// The tokens of a JavaScript, TypeScript or JSON text, whitespace aside: a comment, a string or
/// a template literal is one token, a word one token, any other character one token.
fn source_tokens(text: &str) -> Vec<&str> {
    let mut tokens = Vec::new();
    let mut rest = text.trim_start();

    while let Some(first) = rest.chars().next() {
        let length = token_length(rest, first);
        let (token, after) = rest.split_at(length);

        tokens.push(token);
        rest = after.trim_start();
    }

    tokens
}

/// The length in bytes of the token `rest` starts with, `first` its first character; always on a
/// character boundary and at least that character.
fn token_length(rest: &str, first: char) -> usize {
    if rest.starts_with("//") {
        return rest.find('\n').unwrap_or(rest.len());
    }

    if rest.starts_with("/*") {
        return rest.find("*/").map_or(rest.len(), |end| end + "*/".len());
    }

    let length = match first {
        '"' | '\'' => quoted_length(rest, first),
        '`' => template_length(rest),
        character if is_word_character(character) => rest
            .find(|character: char| !is_word_character(character))
            .unwrap_or(rest.len()),
        character => character.len_utf8(),
    };

    length.max(first.len_utf8())
}

/// A word character: ASCII letters and digits, `_`, `$` and every non-ASCII character.
fn is_word_character(character: char) -> bool {
    character.is_ascii_alphanumeric() || matches!(character, '_' | '$') || !character.is_ascii()
}

/// The length of a quoted string, its closing quote included; an unterminated one ends at its line.
fn quoted_length(rest: &str, quote: char) -> usize {
    let mut characters = rest.char_indices().skip(1);

    while let Some((index, character)) = characters.next() {
        match character {
            '\\' => {
                characters.next();
            }
            '\n' => return index,
            _ if character == quote => return index + character.len_utf8(),
            _ => {}
        }
    }

    rest.len()
}

/// The length of a template literal, its `${...}` substitutions included.
fn template_length(rest: &str) -> usize {
    let mut characters = rest.char_indices().skip(1).peekable();
    let mut substitution_depth = 0_usize;

    while let Some((index, character)) = characters.next() {
        match character {
            '\\' => {
                characters.next();
            }
            '`' if substitution_depth == 0 => return index + 1,
            '$' if characters.peek().is_some_and(|(_, next)| *next == '{') => {
                characters.next();
                substitution_depth += 1;
            }
            '}' if substitution_depth > 0 => substitution_depth -= 1,
            _ => {}
        }
    }

    rest.len()
}

/// The mismatches of a Rust manifest at `manifest_path` against the TypeScript one: version 2,
/// each `source` and `sha256` the SHA-256 of the file now in `directory` (read right after the
/// step that wrote the manifest), then `owner` and the ordered paths by value, and the TypeScript
/// hash of each file whose bytes are equal on both sides. `expected_bytes_of` gives the
/// TypeScript bytes of a path relative to the manifest directory, when the TypeScript wrote it.
#[must_use]
pub fn manifest_v2_mismatches(
    manifest_path: &str,
    expected_text: &str,
    actual_text: &str,
    directory: &Utf8Path,
    expected_bytes_of: &dyn Fn(&str) -> Option<Vec<u8>>,
) -> Vec<Mismatch> {
    let pointer = generated_file_pointer(manifest_path);

    let (Ok(expected), Ok(actual)) = (
        serde_json::from_str::<Value>(expected_text),
        serde_json::from_str::<Value>(actual_text),
    ) else {
        return vec![value_mismatch(&pointer, None, None)];
    };

    let mut mismatches = Vec::new();

    if actual.get("version").and_then(Value::as_u64) != Some(RUST_MANIFEST_VERSION) {
        mismatches.push(value_mismatch(
            &format!("{pointer}/version"),
            Some(Value::from(RUST_MANIFEST_VERSION)),
            actual.get("version").cloned(),
        ));
    }

    if expected.get("owner") != actual.get("owner") {
        mismatches.push(value_mismatch(
            &format!("{pointer}/owner"),
            expected.get("owner").cloned(),
            actual.get("owner").cloned(),
        ));
    }

    let expected_files = manifest_files(&expected);
    let actual_files = manifest_files(&actual);
    let expected_paths: Vec<Option<&str>> = expected_files
        .iter()
        .map(|file| text_member(file, "path"))
        .collect();
    let actual_paths: Vec<Option<&str>> = actual_files
        .iter()
        .map(|file| text_member(file, "path"))
        .collect();

    if expected_paths != actual_paths {
        mismatches.push(value_mismatch(
            &format!("{pointer}/files"),
            Some(path_list(&expected_paths)),
            Some(path_list(&actual_paths)),
        ));
    }

    for (index, file) in actual_files.iter().enumerate() {
        let file_pointer = format!("{pointer}/files/{index}");

        mismatches.extend(file_hash_mismatches(&file_pointer, file, directory));
        mismatches.extend(equal_bytes_hash_mismatch(
            &file_pointer,
            file,
            &expected_files,
            directory,
            expected_bytes_of,
        ));
    }

    mismatches
}

fn manifest_files(manifest: &Value) -> Vec<&Value> {
    manifest
        .get("files")
        .and_then(Value::as_array)
        .map_or_else(Vec::new, |files| files.iter().collect())
}

fn text_member<'value>(value: &'value Value, member: &str) -> Option<&'value str> {
    value.get(member).and_then(Value::as_str)
}

fn path_list(paths: &[Option<&str>]) -> Value {
    Value::Array(
        paths
            .iter()
            .map(|path| path.map_or(Value::Null, |path| Value::String(path.to_owned())))
            .collect(),
    )
}

/// The `source` and `sha256` of one Rust manifest entry against the bytes on disk.
fn file_hash_mismatches(file_pointer: &str, file: &Value, directory: &Utf8Path) -> Vec<Mismatch> {
    let on_disk = text_member(file, "path")
        .and_then(|path| std::fs::read(directory.join(path)).ok())
        .map(|bytes| sha256_hex(&bytes));

    ["source", "sha256"]
        .into_iter()
        .filter(|member| on_disk.is_none() || on_disk.as_deref() != text_member(file, member))
        .map(|member| {
            value_mismatch(
                &format!("{file_pointer}/{member}"),
                on_disk.clone().map(Value::String),
                file.get(member).cloned(),
            )
        })
        .collect()
}

/// The TypeScript hash of a file whose bytes are equal on both sides must equal the Rust one.
fn equal_bytes_hash_mismatch(
    file_pointer: &str,
    file: &Value,
    expected_files: &[&Value],
    directory: &Utf8Path,
    expected_bytes_of: &dyn Fn(&str) -> Option<Vec<u8>>,
) -> Option<Mismatch> {
    let path = text_member(file, "path")?;
    let expected_bytes = expected_bytes_of(path)?;
    let actual_bytes = std::fs::read(directory.join(path)).ok()?;

    if expected_bytes != actual_bytes {
        return None;
    }

    let expected_sha256 = expected_files
        .iter()
        .find(|expected| text_member(expected, "path") == Some(path))
        .and_then(|expected| text_member(expected, "sha256"))?;

    if Some(expected_sha256) == text_member(file, "sha256") {
        return None;
    }

    Some(value_mismatch(
        &format!("{file_pointer}/sha256"),
        Some(Value::String(expected_sha256.to_owned())),
        file.get("sha256").cloned(),
    ))
}

fn value_mismatch(pointer: &str, expected: Option<Value>, actual: Option<Value>) -> Mismatch {
    Mismatch {
        pointer: Some(pointer.to_owned()),
        kind: MismatchKind::Value,
        expected,
        actual,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn no_package(_: &str) -> Option<String> {
        None
    }

    #[test]
    fn a_trailing_comma_is_a_token_and_layout_is_not() {
        let expected = "// Generated by probe-server 1.0.0 from api \"tasks\". Do not edit.\nexport const a = { b: 1 };\n";
        let actual = "// Generated by seampact 2.0.0 (probe-server) from api \"tasks\". Do not edit.\nexport const a = {\n  b: 1,\n};\n";

        assert_eq!(
            generated_file_mismatch("out/a.js", expected, actual, &no_package),
            Some(Mismatch {
                pointer: Some("/out~1a.js".to_owned()),
                kind: MismatchKind::Value,
                expected: Some(Value::String(String::new())),
                actual: Some(Value::String(",".to_owned())),
            }),
            "a trailing comma before a brace is a token"
        );
        assert_eq!(
            generated_file_mismatch(
                "out/a.json",
                "{ \"b\": 1 }\n",
                "{\n  \"b\": 1\n}\n",
                &no_package
            ),
            None
        );
    }

    #[test]
    fn the_header_keeps_the_short_id_and_the_api() {
        let renamed =
            |package: &str| (package == "@seampact/codegen-hono").then(|| "hono".to_owned());
        let expected =
            "// Generated by @seampact/codegen-hono 1.4.0 from api \"tasks\". Do not edit.\nx;\n";

        assert_eq!(
            generated_file_mismatch(
                "a.ts",
                expected,
                "// Generated by seampact 2.0.0 (hono) from api \"tasks\". Do not edit.\nx;\n",
                &renamed
            ),
            None
        );
        assert!(
            generated_file_mismatch(
                "a.ts",
                expected,
                "// Generated by seampact 2.0.0 (hono) from api \"other\". Do not edit.\nx;\n",
                &renamed
            )
            .is_some()
        );
    }

    #[test]
    fn the_two_typescript_rewrites_are_undone() {
        let expected = "type A<T,> = T;\ntype U =\n  | \"a\"\n  | \"b\";\n";
        let actual = "type A<T> = T;\ntype U = \"a\" | \"b\";\n";

        assert_eq!(
            generated_file_mismatch("a.ts", expected, actual, &no_package),
            None
        );
        assert!(generated_file_mismatch("a.js", "f(a,)", "f(a)", &no_package).is_some());
    }

    #[test]
    fn strings_templates_and_comments_are_one_token() {
        let expected = "const a = `x ${ b } y`; // a  comment\nconst c = 'p  q';";
        let actual = "const a = `x ${ b } y`; // a comment\nconst c = 'p  q';";

        let mismatch = generated_file_mismatch("a.js", expected, actual, &no_package);

        assert_eq!(
            mismatch.and_then(|mismatch| mismatch.expected),
            Some(Value::String("// a  comment".to_owned()))
        );
    }

    #[test]
    fn a_manifest_directory_holds_the_files_below_it() {
        assert_eq!(
            manifest_directory("out/.seampact-manifest.json"),
            Some("out")
        );
        assert_eq!(manifest_directory(".seampact-manifest.json"), Some(""));
        assert_eq!(manifest_directory("out/x.json"), None);
        assert_eq!(
            holding_directory("out/sub/a.ts", &["out", "out/sub"]),
            Some("out/sub")
        );
        assert_eq!(holding_directory("outer/a.ts", &["out"]), None);
    }
}
