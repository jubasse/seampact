// seampact-spring-runtime (ADR 0025): the boundary runtime the Spring Boot target's generated code imports, the
// package `io.github.jubasse.seampact.springboot.runtime`. Spring Data and Spring Security are optional: only
// `SpringDataPages` and `SecurityRefusals` name them, and an app that uses them has them.

import io.github.jubasse.seampact.conventions.WriteVersionConstant
import org.gradle.api.publish.maven.tasks.GenerateMavenPom

plugins {
    id("seampact.library-module")
    `java-library`
}

description = "The boundary runtime the Spring Boot code generated by seampact imports."

val springBootVersion: String = libs.versions.spring.boot.get()

dependencies {
    api(project(":seampact-hooks"))
    api("org.springframework.boot:spring-boot-starter-webmvc:$springBootVersion")

    // Optional: the versions come from the app's Spring Boot line, so the published POM names neither.
    compileOnly(platform(libs.spring.boot.dependencies))
    compileOnly("org.springframework.data:spring-data-commons")
    compileOnly(libs.spring.boot.starter.security)

    testImplementation(platform(libs.junit.bom))
    testImplementation(libs.junit.jupiter)
    testRuntimeOnly(libs.junit.platform.launcher)
}

// The runtime's version constant, read by the generate-time check and the boot check (ADR 0025, G2 and G3).
val writeRuntimeVersion = tasks.register<WriteVersionConstant>("writeRuntimeVersion") {
    version = project.version.toString()
    className = "io.github.jubasse.seampact.springboot.runtime.SeampactRuntimeVersion"
    documentation = "The version of seampact-spring-runtime, which the generated code's version is checked against."
    outputDirectory = layout.buildDirectory.dir("generated/runtime-version")
}

sourceSets.main {
    java.srcDir(writeRuntimeVersion)
}

tasks.withType<JavaCompile>().configureEach {
    options.compilerArgs.addAll(listOf("-Xlint:all", "-Werror"))
}

tasks.test {
    useJUnitPlatform()
}

// The published POM names no Spring module: the app's Spring Boot provides them, so adding seampact never moves the
// app's Spring Boot version.
val generatePublishedPom = tasks.named<GenerateMavenPom>("generatePomFileForMavenPublication")
val checkPublishedPom = tasks.register("checkPublishedPom") {
    description = "Checks that the published POM of seampact-spring-runtime depends on no Spring module."
    inputs.files(generatePublishedPom)
    val publishedPom = generatePublishedPom.map { it.destination }

    doLast {
        val springGroups = Regex("<groupId>(org\\.springframework[^<]*)</groupId>").findAll(publishedPom.get().readText()).map { it.groupValues[1] }.toList()
        check(springGroups.isEmpty()) {
            "the published POM of seampact-spring-runtime depends on $springGroups; fix: declare every Spring module compileOnly, the app's Spring Boot provides it."
        }
    }
}

tasks.check {
    dependsOn(checkPublishedPom)
}
