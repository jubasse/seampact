package io.github.jubasse.seampact.ir.write

import java.util.Locale

/** One file a target generated: a relative POSIX [path] inside its output root and its text. */
public data class GeneratedFile(val path: String, val contents: String)

/** Why the writer refuses a write: the codes of the Node writer (`codegen-core`), a [message] and its [fix]. */
public data class WriterRefusal(val code: String, val message: String, val fix: String)

/** What the generated header names: the target's artefact, its version and the api (ADR 0015). */
public data class HeaderSource(val generator: String, val version: String, val api: String)

/** The writer's own file in each target's output directory; no target may generate it. */
public const val MANIFEST_FILE_NAME: String = ".seampact-manifest.json"

// The extensions the JVM targets emit, each with the line comment that carries the header; JSON has no comment
// syntax, the manifest covers it.
private const val NO_LINE_COMMENT = ""
private val LINE_COMMENT_BY_EXTENSION = mapOf(".java" to "//", ".kt" to "//", ".properties" to "#", ".json" to NO_LINE_COMMENT)

/** The one line every generated file with comment syntax starts with (ADR 0015 "The generated header"). */
public fun generatedHeader(source: HeaderSource): String =
    "Generated by ${source.generator} ${source.version} from api \"${source.api}\". Do not edit."

/** The outcome of adding the header: the files, or one refusal per file of an extension the writer does not know. */
public sealed interface HeaderOutcome {
    public data class Finished(val files: List<GeneratedFile>) : HeaderOutcome

    public data class Refused(val refusals: List<WriterRefusal>) : HeaderOutcome
}

/** Adds the generated header to each file whose extension has line comments, as `finish-files.ts` does. */
public fun withGeneratedHeader(files: List<GeneratedFile>, header: HeaderSource): HeaderOutcome {
    val line = generatedHeader(header)
    val finished = mutableListOf<GeneratedFile>()
    val refusals = mutableListOf<WriterRefusal>()

    for (file in files) {
        when (val comment = LINE_COMMENT_BY_EXTENSION[extensionOf(file.path)]) {
            null -> refusals += WriterRefusal(
                "file.extension.unsupported",
                "The target generated '${file.path}', whose extension is not one the writer knows (${LINE_COMMENT_BY_EXTENSION.keys.joinToString(", ")}).",
                "Report this to the target's maintainers: the writer must learn the extension before a target emits it.",
            )
            NO_LINE_COMMENT -> finished += file
            else -> finished += file.copy(contents = "$comment $line\n${file.contents}")
        }
    }

    return if (refusals.isEmpty()) HeaderOutcome.Finished(finished) else HeaderOutcome.Refused(refusals)
}

private fun extensionOf(path: String): String {
    val fileName = path.substringAfterLast('/')
    val dot = fileName.lastIndexOf('.')

    return if (dot <= 0) "" else fileName.substring(dot)
}

/** Why a path is not a relative POSIX path that stays inside the output directory, or null when it is. */
internal fun unsafePathReason(path: String): String? = when {
    path.isEmpty() -> "it is empty"
    '\\' in path -> "it contains a backslash; paths use '/'"
    path.startsWith("/") || Regex("^[A-Za-z]:").containsMatchIn(path) -> "it has an absolute prefix"
    '\u0000' in path -> "it contains a NUL character"
    path.split("/").any { it == "" || it == "." || it == ".." } -> "it has an empty, '.' or '..' segment"
    else -> null
}

/** The paths seen so far, by exact spelling and by case-folded key. */
private class SeenPaths {
    val exactPaths = HashSet<String>()
    val fileByFoldedPath = HashMap<String, String>()
    val directoryByFoldedPath = HashMap<String, String>()

    fun remember(path: String) {
        exactPaths += path
        fileByFoldedPath.putIfAbsent(caseFolded(path), path)

        for (directory in directoryPrefixes(path)) directoryByFoldedPath.putIfAbsent(caseFolded(directory), directory)
    }
}

/** Each unsafe, duplicate or reserved path refused, else the files in code-unit order of path. */
internal fun checkGeneratedPaths(files: List<GeneratedFile>): Pair<List<GeneratedFile>, List<WriterRefusal>> {
    val seen = SeenPaths()
    val refusals = mutableListOf<WriterRefusal>()

    for (file in files) {
        val unsafe = unsafePathReason(file.path)
        val reason = unsafe ?: pathRefusalReason(file.path, seen)

        if (reason != null) {
            refusals += WriterRefusal(
                "file.path.invalid",
                "The target generated the path '${file.path}', and $reason.",
                "Report this to the target's maintainers, or, if two paths differ only by letter case, rename one of the two contract names: a target emits distinct relative POSIX paths inside its output root.",
            )
        }

        if (unsafe == null) seen.remember(file.path)
    }

    return Pair(files.sortedWith { left, right -> left.path.compareTo(right.path) }, refusals)
}

private fun pathRefusalReason(path: String, seen: SeenPaths): String? {
    if (path in seen.exactPaths) return "it is generated twice"

    val folded = caseFolded(path)
    val earlierFile = seen.fileByFoldedPath[folded]
    val earlierDirectory = seen.directoryByFoldedPath[folded]

    return when {
        earlierFile != null -> "it differs only by letter case from '$earlierFile'"
        earlierDirectory != null -> "it is a file, and an earlier path uses '$earlierDirectory' as a directory"
        else -> directoryRefusalReason(path, seen) ?: manifestRefusalReason(path)
    }
}

private fun directoryRefusalReason(path: String, seen: SeenPaths): String? {
    for (directory in directoryPrefixes(path)) {
        val folded = caseFolded(directory)
        val fileAtDirectory = seen.fileByFoldedPath[folded]
        val earlierDirectory = seen.directoryByFoldedPath[folded]

        if (fileAtDirectory != null) return "its directory '$directory' is also the file '$fileAtDirectory'"

        if (earlierDirectory != null && earlierDirectory != directory) {
            return "its directory '$directory' differs only by letter case from the directory '$earlierDirectory' of an earlier path"
        }
    }

    return null
}

private fun manifestRefusalReason(path: String): String? =
    if (path.substringAfterLast('/') == MANIFEST_FILE_NAME) "'$MANIFEST_FILE_NAME' is the writer's manifest" else null

// Each directory of the path, from the outermost: `a/b/c.java` has `a` and `a/b`.
private fun directoryPrefixes(path: String): List<String> {
    val segments = path.split("/")

    return (1 until segments.size).map { count -> segments.take(count).joinToString("/") }
}

// The key two paths share on a case-insensitive file system. Lower, upper, then lower case: the same answer in
// the four writers (a plain case fold treats the capital sharp s and the dotless i differently), as ADR 0015 says.
internal fun caseFolded(path: String): String =
    path.lowercase(Locale.ROOT).uppercase(Locale.ROOT).lowercase(Locale.ROOT)
