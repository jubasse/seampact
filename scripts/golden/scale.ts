import {
  API_EXTRA_ERROR_STEMS,
  BILLING_FAMILIES,
  BILLING_GENERATED_ACTIONS,
  BILLING_GENERATED_RESOURCES,
  DOMAIN_ENUMS,
  ERROR_STEMS,
  INVENTORY_FAMILIES,
  INVENTORY_GENERATED_ACTIONS,
  INVENTORY_GENERATED_RESOURCES,
  NOTIFY_FAMILIES,
  type ResourceName,
  SCALE_SEED,
  VALUE_ADJECTIVES,
  VALUE_NOUNS,
  VALUE_SCHEMA_COUNT,
} from "./scale-words.ts";
import { pick, seededRandom } from "./seeded-random.ts";

// The scale fixture generator (FR-18): the volumes the hand-written part of fixtures/scale does not reach. The
// output is a pure function of SCALE_SEED, committed, and checked for staleness by `scripts/golden --check`.

export const SCALE_DIRECTORY = "fixtures/scale";

// Surfaces whose routes the generator writes; every other surface of the fixture is hand-written.
export const GENERATED_SURFACES: Record<string, string[]> = {
  inventory: ["bulk"],
  billing: ["app", "hooks"],
};

// Resources written by hand, in the order of the global resource index the generated references continue from.
export const HAND_WRITTEN_RESOURCE_COUNT = { inventory: 4, notify: 2 };

// Codes the hand-written files attach themselves; the generator attaches the others.
const HAND_ATTACHED_CODES = new Set([
  "stock.missing",
  "stock.locked",
  "shelf.missing",
  "shelf.locked",
]);

const ERROR_EXAMPLE_COUNT = 84;
const FIRST_GENERATED_INVENTORY_INDEX = HAND_WRITTEN_RESOURCE_COUNT.inventory;
const FIRST_BILLING_INDEX = FIRST_GENERATED_INVENTORY_INDEX + INVENTORY_GENERATED_RESOURCES.length;
const ODD_VALUE_SCHEMAS = VALUE_SCHEMA_COUNT / 2;
const HEADER = `# Generated by scripts/golden (seed ${SCALE_SEED}); \`node --experimental-transform-types --import ./scripts/ir-models/register.ts scripts/golden/cli.ts --write\` rewrites it.`;

function lowerFirst(text: string): string {
  return text.charAt(0).toLowerCase() + text.slice(1);
}

export function valueSchemaName(index: number): string {
  const adjective = VALUE_ADJECTIVES[Math.floor(index / VALUE_NOUNS.length)];
  const noun = VALUE_NOUNS[index % VALUE_NOUNS.length];

  if (adjective === undefined || noun === undefined) throw new Error(`no value schema ${index}`);

  return adjective + noun;
}

/** The two value schemas a resource's `detail` and `extra` properties use; together they cover every odd one. */
function valueReferencesOf(resourceIndex: number): { detail: string; extra: string } {
  const odd = (offset: number): number =>
    2 * ((2 * resourceIndex + offset) % ODD_VALUE_SCHEMAS) + 1;

  return { detail: valueSchemaName(odd(0)), extra: valueSchemaName(odd(1)) };
}

function enumsOf(resourceIndex: number): { state: string; kind: string } {
  const named = (offset: number): string =>
    DOMAIN_ENUMS[(resourceIndex + offset) % DOMAIN_ENUMS.length]?.name ?? "";

  return { state: named(0), kind: named(3) };
}

function firstMember(enumName: string): string {
  return DOMAIN_ENUMS.find((each) => each.name === enumName)?.values[0] ?? "";
}

interface ErrorCode {
  code: string;
  status: number;
  nature: string;
  params: string;
  example: string;
}

const PARAMS: { params: string; example: string }[] = [
  { params: "{ target: { type: string, maxLength: 80 } }", example: "{ target: 'sample' }" },
  {
    params: "{ lockedBy: UserId }",
    example: "{ lockedBy: '6f1c2a4e-8b1d-4c3a-9f2e-1d5b7a9c0e42' }",
  },
  {
    params: "{ expiredAt: { type: string, format: date-time } }",
    example: "{ expiredAt: '2027-01-15T09:30:00Z' }",
  },
  {
    params: "{ existingId: UserId }",
    example: "{ existingId: '6f1c2a4e-8b1d-4c3a-9f2e-1d5b7a9c0e42' }",
  },
  { params: "{ limit: { type: integer, minimum: 0 } }", example: "{ limit: 100 }" },
  { params: "{ field: { type: string, maxLength: 80 } }", example: "{ field: 'name' }" },
  { params: "{ waitMs: { type: integer, minimum: 0 } }", example: "{ waitMs: 2000 }" },
  {
    params: "{ reason: { type: string, maxLength: 200 } }",
    example: "{ reason: 'Held for review.' }",
  },
  { params: "{ issues: Issues }", example: "{ issues: [{ pointer: /name, rule: minLength }] }" },
  {
    params: "{ currentVersion: { type: integer, minimum: 1 } }",
    example: "{ currentVersion: 3 }",
  },
];

function familyCodes(families: readonly string[]): ErrorCode[] {
  return families.flatMap((family) =>
    ERROR_STEMS.map((entry, index) => ({
      code: `${family}.${entry.stem}`,
      status: entry.status,
      nature: entry.nature,
      params: PARAMS[index]?.params ?? "",
      example: PARAMS[index]?.example ?? "",
    })),
  );
}

function apiExtraCodes(): ErrorCode[] {
  return API_EXTRA_ERROR_STEMS.map((entry, index) => ({
    code: `api.${entry.stem}`,
    status: entry.status,
    nature: entry.nature,
    params: PARAMS[index]?.params ?? "",
    example: PARAMS[index]?.example ?? "",
  }));
}

function errorsFile(): string {
  const declared = [
    ...apiExtraCodes(),
    ...familyCodes([...INVENTORY_FAMILIES, ...BILLING_FAMILIES, ...NOTIFY_FAMILIES]),
  ];
  const blocks = declared.map(
    (entry) =>
      `${entry.code}:\n  status: ${entry.status}\n  nature: ${entry.nature}\n  params: ${entry.params}\n  example: ${entry.example}\n`,
  );

  return `${HEADER}
api.schema_invalid:
  status: 400
  nature: refused
  params: { issues: Issues }
  example: { issues: [{ pointer: /name, rule: minLength }] }
api.rate_limited:
  status: 429
  nature: unavailable
  params: { retryAfterMs: { type: integer, minimum: 0, maximum: 9007199254740991 } }
  example: { retryAfterMs: 1500 }
${blocks.join("")}`;
}

function enumsFile(): string {
  const domain = DOMAIN_ENUMS.map(
    (entry) =>
      `${entry.name}: { values: [${entry.values.join(", ")}], reason: "${entry.name} is local to this workspace." }\n`,
  );

  return `${HEADER}
Role: { values: [owner, editor, viewer], reason: "Roles are local to this workspace." }
Surface: { values: [app, studio], reason: "The product's entry points." }
${domain.join("")}`;
}

function valuesFile(): string {
  const random = seededRandom(SCALE_SEED);
  const blocks: string[] = [];

  for (let index = 0; index < VALUE_SCHEMA_COUNT; index++) {
    const enumName = DOMAIN_ENUMS[index % DOMAIN_ENUMS.length]?.name ?? "";
    const labelLength = pick(random, [40, 60, 80, 120]);
    const quantityMaximum = pick(random, [100, 1000, 10_000]);
    const inner = index % 2 === 1 ? `    inner: ${valueSchemaName(index - 1)}\n` : "";

    blocks.push(
      `${valueSchemaName(index)}:
  type: object
  required: [label]
  properties:
    label: { type: string, minLength: 1, maxLength: ${labelLength} }
    ${lowerFirst(enumName)}: { enum: ${enumName} }
    quantity: { type: integer, minimum: 0, maximum: ${quantityMaximum} }
${inner}`,
    );
  }

  return `${HEADER}\n${blocks.join("")}`;
}

interface Resource extends ResourceName {
  index: number;
  verb?: string;
}

function resourcesOf(
  names: readonly ResourceName[],
  firstIndex: number,
  verbs: readonly string[],
): Resource[] {
  return names.map((name, offset) => ({
    ...name,
    index: firstIndex + offset,
    ...(verbs[offset] === undefined ? {} : { verb: verbs[offset] }),
  }));
}

function resourceSchemas(resource: Resource, random: () => number): string {
  const { singular } = resource;
  const identifier = `${lowerFirst(singular)}Id`;
  const { state, kind } = enumsOf(resource.index);
  const { detail, extra } = valueReferencesOf(resource.index);
  const nameLength = pick(random, [80, 100, 120, 160, 200]);
  const action =
    resource.verb === undefined
      ? ""
      : `${capitalised(resource.verb)}${singular}Input:
  type: object
  required: [reason]
  properties:
    reason: { type: string, minLength: 1, maxLength: 200 }
    notify: { type: boolean }
`;

  return `${singular}Id: { type: string, format: uuid }
${singular}:
  type: object
  required: [${identifier}, name, state, kind, detail, createdAt, version]
  properties:
    ${identifier}: ${singular}Id
    name: { type: string, minLength: 1, maxLength: ${nameLength} }
    state: { enum: ${state} }
    kind: { enum: ${kind} }
    detail: ${detail}
    extra: ${extra}
    createdAt: { type: string, format: date-time }
    version: { type: integer, minimum: 1 }
Create${singular}:
  pick: { from: ${singular}, fields: [name, state, kind] }
Update${singular}:
  pick: { from: ${singular}, fields: [name, state] }
  required: []
${action}`;
}

function capitalised(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

interface Attachment {
  code: string;
  example: string;
}

/** The codes a pool attaches to each resource, round-robin, with the example a route repeats for it. */
function attachmentsOf(resources: readonly Resource[], pool: readonly ErrorCode[]): Attachment[][] {
  const perResource: Attachment[][] = resources.map(() => []);

  pool.forEach((entry, position) => {
    perResource[position % resources.length]?.push({ code: entry.code, example: entry.example });
  });

  return perResource;
}

function resourceRoutes(
  resource: Resource,
  attachments: readonly Attachment[],
  errorExamplesLeft: { count: number },
): string {
  const { singular, plural } = resource;
  const identifier = `${lowerFirst(singular)}Id`;
  const { state, kind } = enumsOf(resource.index);
  const attached = attachments.map((each) => `${each.code}: {}`);
  const errorsBlock =
    attached.length === 0 ? "" : `errors:\n${attached.map((line) => `  ${line}\n`).join("")}`;
  const exampled = attachments.slice(0, Math.max(errorExamplesLeft.count, 0));

  errorExamplesLeft.count -= exampled.length;
  const getLines = exampled.map(
    (each, position) => `      e${position + 1}: { error: ${each.code}, value: ${each.example} }\n`,
  );
  const getBlock =
    exampled.length === 0 ? "  get: {}\n" : `  get:\n    examples:\n${getLines.join("")}`;
  const action =
    resource.verb === undefined
      ? ""
      : `member:
  routes:
    ${resource.verb}:
      method: post
      input: ${capitalised(resource.verb)}${singular}Input
      output: ${singular}
      requires: [accountEditor]
`;

  const body = `kind: collection
id: { ${identifier}: ${singular}Id }
item: ${singular}
${errorsBlock}ops:
  list: {}
${getBlock}  create:
    input: Create${singular}
    requires: [writeThrottle, accountEditor]
    examples:
      minimal: { request: true, value: { name: 'Sample ${lowerFirst(singular)}', state: ${firstMember(state)}, kind: ${firstMember(kind)} } }
  update: { input: Update${singular}, requires: [accountEditor] }
  delete: { requires: [accountEditor] }
${action}`;

  return `${plural}:\n${indented(body, 2)}`;
}

function indented(text: string, spaces: number): string {
  const margin = " ".repeat(spaces);

  return text
    .split("\n")
    .map((line) => (line === "" ? line : margin + line))
    .join("\n");
}

function accountScope(name: string, operations: string, routes: string): string {
  return `${name}:
  kind: collection
  id: { accountId: AccountId }
  item: Account
  ops: [${operations}]
  member:
    scopes: { account: path.accountId }
    routes:
${indented(routes, 6)}`;
}

function surfacesOf(
  resources: readonly Resource[],
  attachments: readonly Attachment[][],
  examplesLeft: { count: number },
): string {
  return resources
    .map((resource, position) =>
      resourceRoutes(resource, attachments[position] ?? [], examplesLeft),
    )
    .join("");
}

function inventoryPool(): ErrorCode[] {
  const family = familyCodes(INVENTORY_FAMILIES).filter(
    (each) => !HAND_ATTACHED_CODES.has(each.code),
  );

  return [...family, ...apiExtraCodes().slice(0, 5)];
}

function billingPool(): ErrorCode[] {
  return [...familyCodes(BILLING_FAMILIES), ...apiExtraCodes().slice(5)];
}

/** Every file of the generated part of the scale fixture, keyed by repository-relative path. */
export function generateScaleFiles(): Map<string, string> {
  const random = seededRandom(SCALE_SEED + 1);
  const inventory = resourcesOf(
    INVENTORY_GENERATED_RESOURCES,
    FIRST_GENERATED_INVENTORY_INDEX,
    INVENTORY_GENERATED_ACTIONS,
  );
  const billing = resourcesOf(
    BILLING_GENERATED_RESOURCES,
    FIRST_BILLING_INDEX,
    BILLING_GENERATED_ACTIONS,
  );
  const examplesLeft = { count: ERROR_EXAMPLE_COUNT };
  const inventoryRoutes = surfacesOf(
    inventory,
    attachmentsOf(inventory, inventoryPool()),
    examplesLeft,
  );
  const billingRoutes = surfacesOf(billing, attachmentsOf(billing, billingPool()), examplesLeft);

  return new Map([
    [`${SCALE_DIRECTORY}/shared/errors.yaml`, errorsFile()],
    [`${SCALE_DIRECTORY}/shared/enums.yaml`, enumsFile()],
    [`${SCALE_DIRECTORY}/shared/values.yaml`, valuesFile()],
    [
      `${SCALE_DIRECTORY}/inventory/generated/schemas.yaml`,
      `${HEADER}\n${inventory.map((each) => resourceSchemas(each, random)).join("")}`,
    ],
    [
      `${SCALE_DIRECTORY}/inventory/generated/surfaces.yaml`,
      `${HEADER}
bulk:
  prefix: /v{version}/bulk
  identity: user
  routes:
${indented(accountScope("tenants", "get", inventoryRoutes), 4)}`,
    ],
    [
      `${SCALE_DIRECTORY}/billing/generated/schemas.yaml`,
      `${HEADER}\n${billing.map((each) => resourceSchemas(each, random)).join("")}`,
    ],
    [
      `${SCALE_DIRECTORY}/billing/generated/surfaces.yaml`,
      `${HEADER}
app:
  prefix: /v{version}
  identity: user
  routes:
${indented(accountScope("accounts", "list, get", billingRoutes), 4)}hooks:
  prefix: /v{version}/hooks
  identity: webhook
  routes:
    stripeEvents:
      method: post
      input: PaymentEvent
      responses:
        204: {}
`,
    ],
  ]);
}
