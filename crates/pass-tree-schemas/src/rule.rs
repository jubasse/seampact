#[cfg(test)]
mod tests {
    use super::*;
    use crate::RULE_IDS;

    #[test]
    fn rule_ids_list_every_rule_once_in_order() {
        let listed: Vec<RuleId> = TreeSchemasRule::ALL
            .iter()
            .map(|rule| rule.rule_id())
            .collect();

        assert_eq!(listed, RULE_IDS);
    }
}
