package io.github.jubasse.seampact.springboot

/**
 * Why the generator writes no file, with the fix. [member] is a JSON Pointer into the IR, or into the target entry for
 * an option or artefact; [operation] is the id of the operation it is in, null outside one.
 */
public data class SpringBootRefusal(
    val code: String,
    val message: String,
    val fix: String,
    val member: String,
    val operation: String? = null,
)

/** The generator refused its input: every reason, named. */
public class SpringBootRefusedException(public val refusals: List<SpringBootRefusal>) :
    RuntimeException(refusals.joinToString("\n") { "${it.code}: ${it.message}" })

/** The delivery that brings a form this release refuses (ADR 0022 "Refused by name or waiting"). */
internal enum class Delivery(val description: String) {
    SPRING_3("it comes with spring-3, the paging, idempotency, cache, concurrency, rule proof and signed route release of this target"),
    SPRING_4("it comes with spring-4, the security, multipart, download and native docs release of this target"),
    AFTER_1_0("no reference contract carries it, so it waits for a consumer after 1.0"),
    CONSUMER("it waits for an app that needs it"),
}

/** Collects refusals; a form shared by several operations is refused once. */
internal class Refusals {
    private val collected = LinkedHashMap<Triple<String, String, String?>, SpringBootRefusal>()

    val isEmpty: Boolean get() = collected.isEmpty()

    fun add(refusal: SpringBootRefusal) {
        collected.putIfAbsent(Triple(refusal.code, refusal.member, refusal.operation), refusal)
    }

    /** A form a later release generates: `<form>.unsupported`, naming that release. */
    fun waiting(form: String, description: String, at: IrPlace, delivery: Delivery) {
        add(
            SpringBootRefusal(
                code = "$form.unsupported",
                message = "$description at ${at.member} is not generated by the spring-boot target yet: ${delivery.description}.",
                fix = "Remove this form from the operations the entry keeps (its `operations` filter), or update the target to a release that generates it.",
                member = at.member,
                operation = at.operation,
            ),
        )
    }

    /** An open-enum value or variant this IR revision knows but the generator does not (ADR 0005 section 3). */
    fun unknownValue(at: IrPlace, value: String) {
        add(
            SpringBootRefusal(
                code = "ir.value.unknown",
                message = "The value '$value' at ${at.member} is not one the spring-boot target knows.",
                fix = "Update the spring-boot target to a release that reads this IR, or compile with the matching seampact version.",
                member = at.member,
                operation = at.operation,
            ),
        )
    }

    /** An IR that breaks a rule the compiler guarantees, such as a reference to a missing schema. */
    fun inconsistent(code: String, description: String, at: IrPlace) {
        add(
            SpringBootRefusal(
                code = code,
                message = "$description at ${at.member}.",
                fix = "Regenerate the IR with seampact: this document is not one it wrote.",
                member = at.member,
                operation = at.operation,
            ),
        )
    }

    fun throwIfAny() {
        if (collected.isNotEmpty()) throw SpringBootRefusedException(collected.values.toList())
    }
}

/** A place in the IR: its JSON Pointer and the operation it is in. */
internal data class IrPlace(val member: String, val operation: String? = null) {
    fun below(vararg segments: Any): IrPlace =
        copy(member = member + segments.joinToString("") { "/" + it.toString().replace("~", "~0").replace("/", "~1") })

    companion object {
        val ROOT: IrPlace = IrPlace("")

        fun ofOperation(index: Int, operationId: String): IrPlace = IrPlace("/operations/$index", operationId)
    }
}
