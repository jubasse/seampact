<?php

declare(strict_types=1);

namespace Seampact\Codegen;

use Seampact\Ir\Config\ConfigProblem;
use Seampact\Ir\Run\GenerationRefusedException;

/** Collects why the generator writes no file, each reason with its code and fix; one form is refused once per place. */
final class Refusals
{
    /** @var array<string, ConfigProblem> */
    private array $problems = [];

    /**
     * @param string $target the target's short name in messages, such as 'laravel'
     * @param string $package the target's Composer package, such as 'seampact/laravel'
     */
    public function __construct(private readonly string $entryId, private readonly string $target, private readonly string $package)
    {
    }

    public function add(string $code, string $message, string $fix, IrPlace $at): void
    {
        $where = "entry '{$this->entryId}' " . ($at->member === '' ? '/' : $at->member)
            . ($at->operation === null ? '' : " (operation '{$at->operation}')");

        $this->problems[$code . "\0" . $where] ??= new ConfigProblem($code, $message, $fix, $where);
    }

    /** A form a later release, or a consumer, brings: `<form>.unsupported`. */
    public function waiting(string $form, string $description, IrPlace $at, Delivery $delivery): void
    {
        $this->add(
            "{$form}.unsupported",
            "{$description} is not generated by the {$this->target} target yet: {$delivery->description()}.",
            "Remove this form from the operations the entry keeps (its `operations` filter), or update {$this->package} to a release that generates it.",
            $at,
        );
    }

    /** A form a named later release of the target brings, such as 'laravel-3': `<form>.unsupported`. */
    public function waitingForRelease(string $form, string $description, IrPlace $at, string $release): void
    {
        $this->add(
            "{$form}.unsupported",
            "{$description} is not generated by the {$this->target} target yet: {$release} generates it.",
            "Remove this form from the operations the entry keeps (its `operations` filter), or update {$this->package} to the release that brings {$release}.",
            $at,
        );
    }

    /** A form this release of the target does not generate, with its arrival: `<form>.unsupported`. */
    public function pending(string $form, string $description, IrPlace $at, FormArrival $arrival): void
    {
        if ($arrival->release !== null) {
            $this->waitingForRelease($form, $description, $at, $arrival->release);
        } elseif ($arrival->delivery !== null) {
            $this->waiting($form, $description, $at, $arrival->delivery);
        }
    }

    /** An IR that breaks a rule the compiler guarantees, such as a reference to a missing schema. */
    public function inconsistent(string $code, string $description, IrPlace $at): void
    {
        $this->add($code, "{$description}.", 'Regenerate the IR with seampact: this document is not one it wrote.', $at);
    }

    /** A value this IR revision allows but this generator does not know (ADR 0005 section 3). */
    public function unknownValue(IrPlace $at, string $value): void
    {
        $this->add(
            'ir.value.unknown',
            "The value '{$value}' is not one the {$this->target} target knows.",
            "Update {$this->package} to a release that reads this IR, or compile with the matching seampact version.",
            $at,
        );
    }

    public function isEmpty(): bool
    {
        return $this->problems === [];
    }

    /** @throws GenerationRefusedException every collected reason */
    public function throwIfAny(): void
    {
        if ($this->problems !== []) {
            throw new GenerationRefusedException(array_values($this->problems));
        }
    }
}
