<?php

declare(strict_types=1);

namespace Seampact\Codegen\Tests;

use PHPUnit\Framework\TestCase;
use Seampact\Codegen\Delivery;
use Seampact\Codegen\FormArrival;
use Seampact\Codegen\IrPlace;
use Seampact\Codegen\Refusals;
use Seampact\Ir\Config\ConfigProblem;
use Seampact\Ir\Run\GenerationRefusedException;

final class RefusalsTest extends TestCase
{
    public function testOneFormIsRefusedOncePerPlace(): void
    {
        $refusals = new Refusals('server', 'symfony', 'seampact/symfony');
        $first = IrPlace::ofOperation(0, 'getTask')->below('paging');

        $refusals->waitingForRelease('paging', 'Paging', $first, 'symfony-3');
        $refusals->waitingForRelease('paging', 'Paging', $first, 'symfony-3');
        $refusals->waitingForRelease('paging', 'Paging', IrPlace::ofOperation(1, 'listTasks')->below('paging'), 'symfony-3');

        $problems = self::problems($refusals);
        self::assertCount(2, $problems);
        self::assertSame("entry 'server' /operations/0/paging (operation 'getTask')", $problems[0]->where);
    }

    public function testAPendingFormNamesItsReleaseOrItsDelivery(): void
    {
        $refusals = new Refusals('server', 'symfony', 'seampact/symfony');

        $refusals->pending('paging', 'Paging', IrPlace::root()->below('a'), FormArrival::inRelease('symfony-3'));
        $refusals->pending('schema.union', 'A union', IrPlace::root()->below('b'), FormArrival::later(Delivery::ContractNeed));

        $problems = self::problems($refusals);
        self::assertSame('paging.unsupported', $problems[0]->code);
        self::assertSame('Paging is not generated by the symfony target yet: symfony-3 generates it.', $problems[0]->message);
        self::assertSame('A union is not generated by the symfony target yet: it waits for a contract that needs it.', $problems[1]->message);
    }

    public function testAPlaceWithAWireNameIsEscapedAsAJsonPointer(): void
    {
        self::assertSame('/params/query/a~1b~0c', IrPlace::root()->below('params', 'query', 'a/b~c')->member);
    }

    /** @return list<ConfigProblem> */
    private static function problems(Refusals $refusals): array
    {
        try {
            $refusals->throwIfAny();
        } catch (GenerationRefusedException $refused) {
            return $refused->problems;
        }

        self::fail('Nothing was refused.');
    }
}
