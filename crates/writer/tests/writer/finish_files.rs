//! The header and the formatting each extension selects, with the refusals of the three other
//! writers' tests: an unknown extension, an unsafe header field and a PHP file without its tag.

use seampact_target::GeneratedFile;
use seampact_writer::{HeaderSource, finish_files};

use crate::support::file;

const HEADER: &str = "Generated by seampact 2.0.0 (probe-server) from api \"tasks\". Do not edit.";

fn header_source() -> HeaderSource<'static> {
    HeaderSource {
        version: "2.0.0",
        short_id: "probe-server",
        api_id: "tasks",
    }
}

fn finished(files: &[GeneratedFile]) -> Vec<GeneratedFile> {
    match finish_files(files.to_vec(), &header_source()) {
        Ok(files) => files,
        Err(refused) => panic!("refused: {refused:?}"),
    }
}

fn refused(files: &[GeneratedFile], header: &HeaderSource<'_>) -> Vec<(String, String)> {
    match finish_files(files.to_vec(), header) {
        Err(refused) => refused
            .0
            .into_iter()
            .map(|refusal| (refusal.code, refusal.message))
            .collect(),
        Ok(files) => panic!("finished: {files:?}"),
    }
}

#[test]
fn a_typescript_file_gets_the_header_and_is_formatted() {
    let done = finished(&[file("a.ts", "export const a   =  1")]);

    assert_eq!(
        done[0].contents,
        format!("// {HEADER}\nexport const a = 1;\n")
    );
}

#[test]
fn a_javascript_file_gets_the_header_and_is_formatted() {
    for path in ["a.js", "a.mjs", "a.cjs"] {
        let done = finished(&[file(path, "const a  = 1")]);

        assert_eq!(
            done[0].contents,
            format!("// {HEADER}\nconst a = 1;\n"),
            "{path}"
        );
    }
}

#[test]
fn a_json_file_has_no_header_and_is_rewritten_with_two_space_indents() {
    let done = finished(&[file("a.json", r#"{"b":[1,2],"a":{}}"#)]);

    assert_eq!(
        done[0].contents,
        "{\n  \"b\": [\n    1,\n    2\n  ],\n  \"a\": {}\n}\n"
    );
}

#[test]
fn a_php_file_gets_the_header_after_its_open_tag_and_crlf_is_read_as_lf() {
    let done = finished(&[file("a.php", "<?php\r\ndeclare(strict_types=1);\r\n")]);

    assert_eq!(
        done[0].contents,
        format!("<?php\n// {HEADER}\ndeclare(strict_types=1);\n")
    );
}

#[test]
fn a_php_file_must_start_with_its_open_tag_on_a_line_of_its_own() {
    let problems = refused(
        &[file("a.php", "<?php declare(strict_types=1);\n")],
        &header_source(),
    );

    assert_eq!(
        problems,
        [(
            "file.php.open-tag".to_owned(),
            "The target generated 'a.php', which does not start with `<?php` on a line of its own."
                .to_owned()
        )]
    );
}

#[test]
fn the_other_extensions_get_a_line_comment_first_and_pass_through() {
    for (path, comment) in [
        ("A.java", "//"),
        ("a.kt", "//"),
        ("a.py", "#"),
        ("a.pyi", "#"),
        ("a.toml", "#"),
        ("a.yaml", "#"),
        ("a.properties", "#"),
    ] {
        let done = finished(&[file(path, "body\n")]);

        assert_eq!(
            done[0].contents,
            format!("{comment} {HEADER}\nbody\n"),
            "{path}"
        );
    }
}

#[test]
fn an_unknown_extension_is_refused_naming_the_known_ones() {
    for path in ["a.rb", "LICENSE", ".ts", "dir.ts/Makefile"] {
        let problems = refused(&[file(path, "")], &header_source());

        assert_eq!(problems.len(), 1, "{path}");
        assert_eq!(problems[0].0, "file.extension.unsupported", "{path}");
        assert!(
            problems[0].1.contains(&format!("'{path}'"))
                && problems[0]
                    .1
                    .ends_with(".json, .php, .java, .kt, .py, .pyi, .toml, .yaml, .properties)."),
            "{path}: {}",
            problems[0].1
        );
    }
}

#[test]
fn source_the_formatter_cannot_parse_is_refused() {
    let problems = refused(&[file("a.ts", "export const = ;")], &header_source());

    assert_eq!(problems[0].0, "file.format.failed");
    assert!(
        problems[0]
            .1
            .starts_with("The writer could not format 'a.ts': "),
        "{}",
        problems[0].1
    );
}

#[test]
fn a_header_field_that_would_leave_the_comment_line_is_refused_once() {
    for (version, short_id, api_id, name) in [
        ("2.0.0\n", "probe", "tasks", "version"),
        ("2.0.0", "pro\u{7f}be", "tasks", "short id"),
        ("2.0.0", "probe", "tasks?>", "api id"),
    ] {
        let header = HeaderSource {
            version,
            short_id,
            api_id,
        };
        let problems = refused(&[file("a.php", "<?php\n"), file("b.ts", "")], &header);

        assert_eq!(problems.len(), 1, "{name}");
        assert_eq!(problems[0].0, "file.header.unsafe", "{name}");
        assert!(
            problems[0].1.starts_with(&format!("The {name} \"")),
            "{name}: {}",
            problems[0].1
        );
    }
}
