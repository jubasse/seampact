"""A page fact 1.0 does not generate is refused by name: the reference's changes feed, whose page carries
`complete`."""

from pathlib import Path

import pytest

from seampact.ir.run.generator import GenerationRefusedError

from .test_drf_generator import contract, generated_files, reference_ir

_REFUSED_FACT = "paging.handlerResult.unsupported"


def test_the_complete_page_fact_of_a_changes_feed_is_refused_by_name(repository_root: Path) -> None:
    ir = contract(reference_ir(repository_root, "tasksPaging"))

    with pytest.raises(GenerationRefusedError) as refused:
        generated_files(ir)

    refused_facts = [problem.message for problem in refused.value.problems if problem.code == _REFUSED_FACT]

    assert len(refused_facts) == 2
    assert "The page fact 'complete' is not generated by the drf target yet" in refused_facts[0]
