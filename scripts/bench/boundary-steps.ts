// The map from the generated boundary's function names to the steps of ADR 0012 "The check order", the one place
// the profile reads. A frame is claimed by its function name, else by the file it is in; a helper several steps
// call stays neutral, so the step that called it takes its time.

export interface BoundaryStep {
  readonly id: string;
  readonly title: string;
  readonly functions: readonly string[];
  // Files of the generated runtime whose anonymous functions belong to the step.
  readonly files: readonly string[];
}

