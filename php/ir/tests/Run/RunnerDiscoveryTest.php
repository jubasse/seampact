<?php

declare(strict_types=1);

namespace Seampact\Ir\Tests\Run;

use PHPUnit\Framework\TestCase;
use Seampact\Ir\Run\Command;
use Seampact\Ir\Tests\Support\GitRepository;
use Seampact\Ir\Tests\Support\TemporaryDirectory;
use Seampact\Ir\Tests\Support\ValidBundle;

/**
 * `vendor/bin/seampact` on a project whose `installed.json` lists fake target packages: the target found by
 * `extra.seampact.generator`, the IR fetched from a git tag, the files written and checked, and each refusal named.
 */
final class RunnerDiscoveryTest extends TestCase
{
    private string $project;

    protected function setUp(): void
    {
        $this->project = TemporaryDirectory::create('seampact-runner-');
        mkdir("{$this->project}/.git");
        GitRepository::withValidBundle("{$this->project}/contract", 'bundle', 'v1');
        TemporaryDirectory::write($this->project, 'composer.json', (string) json_encode([
            'autoload' => ['psr-4' => ['App\\' => 'src/']],
            'extra' => ['seampact' => ['phpPatched' => true]],
        ]));
        TemporaryDirectory::write($this->project, 'vendor/composer/installed.json', (string) json_encode(['packages' => [
            ['name' => 'acme/stub-target', 'version' => '1.2.0', 'extra' => ['seampact' => ['generator' => StubGenerator::class]]],
            ['name' => 'acme/not-a-target', 'version' => '1.0.0'],
            ['name' => 'acme/broken-target', 'version' => '1.0.0', 'extra' => ['seampact' => ['generator' => \stdClass::class]]],
            ['name' => 'acme/throwing-target', 'version' => '1.0.0', 'extra' => ['seampact' => ['generator' => ThrowingGenerator::class]]],
        ]]));
    }

    protected function tearDown(): void
    {
        TemporaryDirectory::remove($this->project);
    }

    public function testGeneratesTheEntryOfAnInstalledTargetAndLeavesTheOthers(): void
    {
        $this->config("{ id: stub, use: acme/stub-target, api: t, options: { flavour: plain } }\n  - { id: web, use: '@seampact/codegen-fetch', api: t }");

        [$exit, $stdout, $stderr] = $this->seampact('generate');

        self::assertSame(Command::EXIT_PASSED, $exit, $stderr);
        self::assertStringContainsString("entry 'stub' wrote 2 file(s), kept 0, removed 0", $stdout);
        self::assertStringContainsString("entry 'web' uses '@seampact/codegen-fetch', which its own runner generates", $stdout);
        self::assertStringStartsWith(
            "<?php\n// Generated by acme/stub-target 1.2.0 from api \"t\". Do not edit.\n\ndeclare(strict_types=1);\n\nnamespace App\\Generated\\stub;\n",
            (string) file_get_contents("{$this->project}/src/Generated/stub/Api.php"),
        );
        self::assertSame("{\"flavour\":\"plain\"}\n", file_get_contents("{$this->project}/src/Generated/stub/options.json"));
        self::assertFileExists("{$this->project}/src/Generated/stub/.seampact-manifest.json");
    }

    public function testChecksTheGeneratedFilesAndRefusesAHandEditUnlessForced(): void
    {
        $this->config('{ id: stub, use: acme/stub-target, api: t }');
        self::assertSame(Command::EXIT_PASSED, $this->seampact('generate')[0]);

        [$exit, $stdout] = $this->seampact('check');
        self::assertSame(Command::EXIT_PASSED, $exit);
        self::assertStringContainsString("source 'contract' passes the pinned-bundle check, integrity " . ValidBundle::integrity(), $stdout);
        self::assertStringContainsString('the generated files match the files on disk', $stdout);

        $file = "{$this->project}/src/Generated/stub/Api.php";
        file_put_contents($file, "<?php\n// mine\n");

        [$exit, , $stderr] = $this->seampact('check');
        self::assertSame(Command::EXIT_REFUSED, $exit);
        self::assertStringContainsString('check.generated.drift', $stderr);

        [$exit, , $stderr] = $this->seampact('generate');
        self::assertSame(Command::EXIT_REFUSED, $exit);
        self::assertStringContainsString('writer.file.edited', $stderr);
        self::assertSame("<?php\n// mine\n", file_get_contents($file));

        self::assertSame(Command::EXIT_PASSED, $this->seampact('generate', '--force')[0]);
        self::assertStringContainsString('final class Api', (string) file_get_contents($file));
    }

    public function testRefusesEachTargetItCannotFindByName(): void
    {
        $this->config("{ id: a, use: acme/missing, api: t }\n  - { id: b, use: acme/not-a-target, api: t }\n  - { id: c, use: acme/broken-target, api: t }");

        [$exit, , $stderr] = $this->seampact('generate');

        self::assertSame(Command::EXIT_REFUSED, $exit);
        self::assertStringContainsString("config.target.missing (entry 'a' use)", $stderr);
        self::assertStringContainsString("config.target.not-a-target (entry 'b' use)", $stderr);
        self::assertStringContainsString("config.target.load-failed (entry 'c' use)", $stderr);
        self::assertDirectoryDoesNotExist("{$this->project}/src");
    }

    public function testNamesATargetWhoseGeneratorFails(): void
    {
        $this->config('{ id: thrower, use: acme/throwing-target, api: t }');

        [$exit, , $stderr] = $this->seampact('generate');

        self::assertSame(Command::EXIT_REFUSED, $exit);
        self::assertStringContainsString("config.target.generate-failed (entry 'thrower' api 't')", $stderr);
        self::assertStringContainsString("'acme/throwing-target'", $stderr);
        self::assertStringContainsString(ThrowingGenerator::MESSAGE, $stderr);
        self::assertDirectoryDoesNotExist("{$this->project}/src");
    }

    public function testReportsAnUnexpectedFailureAsAnInternalErrorOnOneLine(): void
    {
        $this->config('{ id: stub, use: acme/stub-target, api: t }');
        TemporaryDirectory::write($this->project, 'src/Generated', 'a file where the output directory goes');

        [$exit, $stdout, $stderr] = $this->seampact('generate');

        self::assertSame(Command::EXIT_REFUSED, $exit, $stdout);
        self::assertStringStartsWith('seampact: internal error: ', $stderr);
        self::assertSame(1, substr_count(rtrim($stderr), "\n") + 1, $stderr);
    }

    public function testRefusesAnInstalledListInTheComposer1Shape(): void
    {
        $this->config('{ id: stub, use: acme/stub-target, api: t }');
        TemporaryDirectory::write($this->project, 'vendor/composer/installed.json', '[{"name": "acme/stub-target"}]');

        [$exit, , $stderr] = $this->seampact('generate');

        self::assertSame(Command::EXIT_REFUSED, $exit);
        self::assertStringContainsString('config.target.installed-unreadable', $stderr);
    }

    public function testRefusesAnOutDirNoPsr4EntryHolds(): void
    {
        $this->config('{ id: stub, use: acme/stub-target, api: t }', '__generated__');

        [$exit, , $stderr] = $this->seampact('generate');

        self::assertSame(Command::EXIT_REFUSED, $exit);
        self::assertStringContainsString('config.php.autoload-missing', $stderr);
    }

    public function testRefusesAnUnknownCommandAsAUsageError(): void
    {
        [$exit, , $stderr] = $this->seampact('publish');

        self::assertSame(Command::EXIT_USAGE, $exit);
        self::assertStringContainsString("unknown command 'publish'", $stderr);
    }

    private function config(string $targets, string $outDir = 'src/Generated'): void
    {
        TemporaryDirectory::write($this->project, 'seampact.config.yaml', "sources:\n"
            . "  contract: { git: { url: ./contract, tag: v1, directory: bundle }, integrity: '" . ValidBundle::integrity() . "' }\n"
            . "outDir: {$outDir}\nopenapi: none\ntargets:\n  - {$targets}\n");
    }

    /** @return array{int, string, string} */
    private function seampact(string ...$arguments): array
    {
        $stdout = fopen('php://memory', 'w+');
        $stderr = fopen('php://memory', 'w+');
        self::assertIsResource($stdout);
        self::assertIsResource($stderr);

        $environment = [...GitRepository::environment(), 'COMPOSER_CACHE_DIR' => "{$this->project}/cache"];
        $exit = Command::run(array_values($arguments), $this->project, "{$this->project}/vendor", $environment, $stdout, $stderr);

        rewind($stdout);
        rewind($stderr);

        return [$exit, (string) stream_get_contents($stdout), (string) stream_get_contents($stderr)];
    }
}
