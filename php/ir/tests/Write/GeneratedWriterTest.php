<?php

declare(strict_types=1);

namespace Seampact\Ir\Tests\Write;

use PHPUnit\Framework\TestCase;
use Seampact\Ir\Tests\Support\TemporaryDirectory;
use Seampact\Ir\Write\GeneratedFile;
use Seampact\Ir\Write\GeneratedHeader;
use Seampact\Ir\Write\GeneratedWriter;
use Seampact\Ir\Write\HandEditPolicy;
use Seampact\Ir\Write\PlannedWrite;
use Seampact\Ir\Write\WriterRefusal;

/** The writer rules of ADR 0015 "Writing files" and "The generated header", with the Node writer's codes. */
final class GeneratedWriterTest extends TestCase
{
    private string $directory;

    private string $outDir;

    protected function setUp(): void
    {
        $this->directory = TemporaryDirectory::create('seampact-writer-');
        $this->outDir = "{$this->directory}/out";
    }

    protected function tearDown(): void
    {
        TemporaryDirectory::remove($this->directory);
    }

    public function testAddsTheHeaderAfterThePhpOpenTagAndToYamlAndRefusesAnUnknownExtension(): void
    {
        $headed = GeneratedHeader::added(
            [new GeneratedFile('A.php', "<?php\n\nfinal class A {}\n"), new GeneratedFile('routes.yaml', "a: 1\n"), new GeneratedFile('s.json', "{}\n")],
            'seampact/laravel',
            '0.1.0',
            'tasks',
        );

        self::assertEquals([
            new GeneratedFile('A.php', "<?php\n// Generated by seampact/laravel 0.1.0 from api \"tasks\". Do not edit.\n\nfinal class A {}\n"),
            new GeneratedFile('routes.yaml', "# Generated by seampact/laravel 0.1.0 from api \"tasks\". Do not edit.\na: 1\n"),
            new GeneratedFile('s.json', "{}\n"),
        ], $headed);

        self::assertSame(['file.extension.unsupported', 'file.php.open-tag'], self::codes(GeneratedHeader::added(
            [new GeneratedFile('A.txt', 'x'), new GeneratedFile('B.php', "\n<?php\n")],
            'seampact/laravel',
            '0.1.0',
            'tasks',
        )));
    }

    public function testWritesLineFeedFilesSortedWithTheNodeWritersManifest(): void
    {
        $this->write(new GeneratedFile('b/B.php', "\u{FEFF}<?php\r\necho 1;"), new GeneratedFile('A.php', "<?php\n"));

        self::assertSame("<?php\necho 1;\n", file_get_contents("{$this->outDir}/b/B.php"));
        self::assertSame(
            "{\n  \"owner\": \"server\",\n  \"files\": [\n    {\n      \"path\": \"A.php\",\n      \"sha256\": \"" . hash('sha256', "<?php\n")
                . "\"\n    },\n    {\n      \"path\": \"b/B.php\",\n      \"sha256\": \"" . hash('sha256', "<?php\necho 1;\n") . "\"\n    }\n  ]\n}\n",
            file_get_contents("{$this->outDir}/.seampact-manifest.json"),
        );
    }

    public function testKeepsUnchangedFilesAndRemovesStaleOnesWithTheirEmptyDirectories(): void
    {
        $this->write(new GeneratedFile('A.php', "<?php\n"), new GeneratedFile('old/B.php', "<?php\n"));

        $written = GeneratedWriter::commit($this->planned([new GeneratedFile('A.php', "<?php\n")]));

        self::assertSame([[], ['A.php'], ['old/B.php']], [$written->written, $written->unchanged, $written->removed]);
        self::assertDirectoryDoesNotExist("{$this->outDir}/old");
    }

    public function testRefusesAHandEditUnlessAskedToOverwrite(): void
    {
        $this->write(new GeneratedFile('A.php', "<?php\n"));
        file_put_contents("{$this->outDir}/A.php", "<?php\n// mine\n");

        self::assertSame(['writer.file.edited'], $this->refusedCodes(new GeneratedFile('A.php', "<?php\necho 2;\n")));
        self::assertSame(['writer.file.edited'], $this->refusedCodes());

        GeneratedWriter::commit($this->planned([new GeneratedFile('A.php', "<?php\necho 2;\n")], HandEditPolicy::Overwrite));
        self::assertSame("<?php\necho 2;\n", file_get_contents("{$this->outDir}/A.php"));
    }

    public function testRefusesFilesItDidNotGenerateAndAnotherOwnersDirectory(): void
    {
        TemporaryDirectory::write($this->outDir, 'Mine.php', "<?php\n");
        self::assertSame(['writer.file.not-generated'], $this->refusedCodes(new GeneratedFile('Mine.php', "<?php\n")));

        unlink("{$this->outDir}/Mine.php");
        $this->write(new GeneratedFile('A.php', "<?php\n"));
        self::assertSame(['writer.manifest.other-owner'], self::codes(GeneratedWriter::plan($this->outDir, 'other', [], HandEditPolicy::Refuse)));
    }

    public function testRefusesPathsThatLeaveTheOutputDirectory(): void
    {
        foreach (['../A.php', '/A.php', 'a\\A.php', 'a/./A.php', '.seampact-manifest.json'] as $path) {
            self::assertSame(['file.path.invalid'], $this->refusedCodes(new GeneratedFile($path, "<?php\n")), $path);
        }
        self::assertSame(['file.path.invalid'], $this->refusedCodes(new GeneratedFile('A.php', "<?php\n"), new GeneratedFile('A.php', "<?php\n")));

        mkdir("{$this->directory}/elsewhere");
        mkdir($this->outDir);
        symlink("{$this->directory}/elsewhere", "{$this->outDir}/linked");
        self::assertSame(['writer.path.outside'], $this->refusedCodes(new GeneratedFile('linked/A.php', "<?php\n")));
        self::assertFileDoesNotExist("{$this->directory}/elsewhere/A.php");
    }

    public function testRefusesALinkInPlaceOfAGeneratedFileOrOfTheManifest(): void
    {
        $this->write(new GeneratedFile('A.php', "<?php\n"));
        TemporaryDirectory::write($this->directory, 'target.php', "<?php\n");
        unlink("{$this->outDir}/A.php");
        symlink("{$this->directory}/target.php", "{$this->outDir}/A.php");
        self::assertSame(['writer.file.not-generated'], $this->refusedCodes(new GeneratedFile('A.php', "<?php\n")));

        rename("{$this->outDir}/.seampact-manifest.json", "{$this->directory}/manifest.json");
        symlink("{$this->directory}/manifest.json", "{$this->outDir}/.seampact-manifest.json");
        self::assertSame(['writer.manifest.not-regular'], $this->refusedCodes());
    }

    private function write(GeneratedFile ...$files): void
    {
        GeneratedWriter::commit($this->planned(array_values($files)));
    }

    /** @param list<GeneratedFile> $files */
    private function planned(array $files, HandEditPolicy $policy = HandEditPolicy::Refuse): PlannedWrite
    {
        $plan = GeneratedWriter::plan($this->outDir, 'server', $files, $policy);
        self::assertInstanceOf(PlannedWrite::class, $plan);

        return $plan;
    }

    /** @return list<string> */
    private function refusedCodes(GeneratedFile ...$files): array
    {
        return self::codes(GeneratedWriter::plan($this->outDir, 'server', array_values($files), HandEditPolicy::Refuse));
    }

    /**
     * @param PlannedWrite|list<GeneratedFile|WriterRefusal> $outcome
     * @return list<string>
     */
    private static function codes(PlannedWrite|array $outcome): array
    {
        self::assertIsArray($outcome);

        return array_values(array_unique(array_map(
            static fn (object $item): string => $item instanceof WriterRefusal ? $item->code : 'not refused',
            $outcome,
        )));
    }
}
