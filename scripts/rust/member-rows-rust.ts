// Writes `crates/diff-table/src/ir_definition.rs` and `member_rows_data.rs` from `MEMBER_ROWS` of the diff's table.
//
// Run from the repository root with the compiler's flags, then format the crate:
//   node --experimental-transform-types --no-warnings --import ./scripts/ir-models/register.ts \
//     scripts/rust/member-rows-rust.ts
//   cargo fmt -p seampact-diff-table
// The table is the TypeScript's: rerun this after it changes, and `cargo xtask oracle --tool diff` shows any drift.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT } from "../oracle/fixtures.ts";
import { MEMBER_ROWS } from "../../packages/core/diff/src/table/member-rows.ts";

const CRATE_SOURCES = join(REPO_ROOT, "crates/diff-table/src");

type Row = string | { kind: string; case: string };

function pascalCase(text: string): string {
  return text
    .split(".")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

// `ContractIR` is `ContractIr` in Rust.
function definitionVariant(definition: string): string {
  return definition.replace(
    /([A-Z])([A-Z]+)/g,
    (_, first: string, rest: string) => first + rest.toLowerCase(),
  );
}

function rowSource(row: Row): string {
  if (typeof row === "string") return `MemberRow::Kind(DiffKind::${pascalCase(row)})`;

  return `fixed(DiffKind::${pascalCase(row.kind)}, ${JSON.stringify(row.case)})`;
}

function definitionEnumSource(definitions: readonly string[]): string {
  const variants = definitions
    .map((definition) => `    /// \`${definition}\`.\n    ${definitionVariant(definition)},`)
    .join("\n");
  const names = definitions
    .map(
      (definition) =>
        `            Self::${definitionVariant(definition)} => ${JSON.stringify(definition)},`,
    )
    .join("\n");

  return `//! The IR definitions whose members the classification table lists.

// Generated by scripts/rust/member-rows-rust.ts from MEMBER_ROWS; do not edit by hand.

/// An IR definition with a row for each of its members.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum IrDefinition {
${variants}
}

impl IrDefinition {
    /// The definition as the IR schema names it.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
${names}
        }
    }
}
`;
}

function dataSource(): string {
  const definitions = Object.entries(MEMBER_ROWS)
    .map(([definition, rows]) => {
      const members = Object.entries(rows as Record<string, Row>)
        .map(([member, row]) => `            (${JSON.stringify(member)}, ${rowSource(row)}),`)
        .join("\n");

      return `    (\n        IrDefinition::${definitionVariant(definition)},\n        &[\n${members}\n        ],\n    ),`;
    })
    .join("\n");

  return `//! The row of every member of every IR definition.

// Generated by scripts/rust/member-rows-rust.ts from MEMBER_ROWS; do not edit by hand.

use crate::diff_kind::DiffKind;
use crate::ir_definition::IrDefinition;
use crate::member_row::{MemberRow, fixed};

/// The members of one definition, in declaration order.
pub(crate) type DefinitionRows = &'static [(&'static str, MemberRow)];

/// \`MEMBER_ROWS\`: the row of every member of every IR definition.
pub(crate) static MEMBER_ROWS: &[(IrDefinition, DefinitionRows)] = &[
${definitions}
];
`;
}

writeFileSync(
  join(CRATE_SOURCES, "ir_definition.rs"),
  definitionEnumSource(Object.keys(MEMBER_ROWS)),
);
writeFileSync(join(CRATE_SOURCES, "member_rows_data.rs"), dataSource());
