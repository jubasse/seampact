<?php

declare(strict_types=1);

namespace Seampact\Symfony\Tests;

use PHPUnit\Framework\TestCase;
use Psr\Log\NullLogger;
use Seampact\Codegen\Runtime\RuntimeVersion;
use Seampact\Golden\TasksConsistent\Symfony\SeampactOperation as TasksOperation;
use Seampact\Golden\TasksConsistent\Symfony\TasksSeampactBundle;
use Seampact\Golden\TasksConsistent\Symfony\TasksSettings;
use Seampact\Symfony\Runtime\BootCheckPass;
use Seampact\Symfony\Runtime\HookCheckWarmer;
use Seampact\Symfony\Runtime\Hooks;
use Symfony\Component\Config\Resource\FileResource;
use Symfony\Component\DependencyInjection\ContainerBuilder;
use Symfony\Component\DependencyInjection\ServiceLocator;

/** The version check refuses every boot of an api generated by another version, except the command that regenerates it. */
final class RegenerationTest extends TestCase
{
    /** @var array<array-key, mixed>|null */
    private ?array $argumentsBefore = null;

    protected function setUp(): void
    {
        $this->argumentsBefore = is_array($_SERVER['argv'] ?? null) ? $_SERVER['argv'] : null;
    }

    protected function tearDown(): void
    {
        $_SERVER['argv'] = $this->argumentsBefore;
    }

    public function testTheGenerateCommandCompilesAndWarmsUnderARuntimeVersionMismatch(): void
    {
        $_SERVER['argv'] = ['bin/console', '-v', 'seampact:generate'];
        $container = new ContainerBuilder();

        self::bootCheck()->process($container);
        self::hookCheck()->warmUp(sys_get_temp_dir());

        // The container compiled without the check is rebuilt once the contract or the runtime changes.
        $tracked = array_map(static fn (object $resource): string => (string) $resource, $container->getResources());
        $contractFile = (string) (new \ReflectionClass(ForeignVersionContract::class))->getFileName();
        self::assertContains((string) new FileResource($contractFile), $tracked);
    }

    public function testAnyOtherCompileRefusesARuntimeVersionMismatch(): void
    {
        $_SERVER['argv'] = ['bin/console', 'cache:clear'];

        $this->expectException(\LogicException::class);
        $this->expectExceptionMessage(RuntimeVersion::GENERATED_FOR_OTHER_VERSION);
        self::bootCheck()->process(new ContainerBuilder());
    }

    public function testAnyOtherWarmUpRefusesARuntimeVersionMismatch(): void
    {
        $_SERVER['argv'] = ['bin/console', 'cache:warmup'];

        $this->expectException(\LogicException::class);
        $this->expectExceptionMessage(RuntimeVersion::GENERATED_FOR_OTHER_VERSION);
        self::hookCheck()->warmUp(sys_get_temp_dir());
    }

    private static function bootCheck(): BootCheckPass
    {
        return new BootCheckPass(ForeignVersionContract::class, TasksOperation::class, TasksSeampactBundle::BOUNDARY_SERVICE, TasksSeampactBundle::INPUT_RESOLVER_SERVICE, TasksSeampactBundle::SETTINGS_SERVICE, TasksSettings::class, false);
    }

    private static function hookCheck(): HookCheckWarmer
    {
        return new HookCheckWarmer(new Hooks(new ServiceLocator([]), [], [], null, new NullLogger()), ForeignVersionContract::class);
    }
}
