"""Collects why a Python generator writes no file, each reason with its code, message, fix and place, so `generate`
lists every refusal at once; one form is refused once per place."""

from dataclasses import dataclass
from enum import StrEnum

from seampact.ir.config.problem import ConfigProblem
from seampact.ir.run.generator import GenerationRefusedError


class Delivery(StrEnum):
    """Who brings a form the target does not generate yet."""

    CONSUMER = "it comes when a consumer needs it"
    AFTER_V1 = "it comes after 1.0"


@dataclass(frozen=True, slots=True)
class IrPlace:
    """A place in the IR: a JSON pointer, and the operation it sits in."""

    pointer: str
    operation: str | None = None

    def below(self, *keys: str | int) -> "IrPlace":
        return IrPlace(self.pointer + "".join(f"/{key}" for key in keys), self.operation)


class Refusals:
    def __init__(self, entry_id: str, target: str, distribution: str) -> None:
        """`target` is the target's short name in messages (`fastapi`), `distribution` its package
        (`seampact-fastapi`)."""
        self._entry_id = entry_id
        self._target = target
        self._distribution = distribution
        self._problems: dict[tuple[str, str], ConfigProblem] = {}

    def add(self, code: str, message: str, fix: str, at: IrPlace) -> None:
        where = f"entry '{self._entry_id}' {at.pointer or '/'}"

        if at.operation is not None:
            where += f" (operation '{at.operation}')"

        self._problems.setdefault((code, where), ConfigProblem(code, message, fix, where))

    def waiting(self, form: str, description: str, at: IrPlace, delivery: Delivery) -> None:
        """A form a later release, or a consumer, brings: `<form>.unsupported`."""
        self.add(
            f"{form}.unsupported",
            f"{description} is not generated by the {self._target} target yet: {delivery.value}.",
            "Remove this form from the operations the entry keeps (its `operations` filter), or update "
            f"{self._distribution} to a release that generates it.",
            at,
        )

    def inconsistent(self, code: str, description: str, at: IrPlace) -> None:
        """An IR that breaks a rule the compiler guarantees."""
        self.add(code, f"{description}.", "Regenerate the IR with seampact: this document is not one it wrote.", at)

    def unknown_value(self, value: str, at: IrPlace) -> None:
        """A value this IR revision allows but this generator does not know (ADR 0005 section 3)."""
        self.add(
            "ir.value.unknown",
            f"The value '{value}' is not one the {self._target} target knows.",
            f"Update {self._distribution} to a release that reads this IR, or compile with the matching seampact "
            "version.",
            at,
        )

    def is_empty(self) -> bool:
        return not self._problems

    def raise_if_any(self) -> None:
        """Raises `GenerationRefusedError` listing every refusal."""
        if self._problems:
            raise GenerationRefusedError(list(self._problems.values()))
