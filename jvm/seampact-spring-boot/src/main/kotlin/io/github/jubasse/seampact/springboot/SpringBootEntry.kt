package io.github.jubasse.seampact.springboot

import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive

/**
 * One spring-boot target entry of the app config, as a build plugin reads it (ADR 0011 "The app config"): its [id],
 * its `options`, `artefacts`, `frameworkDocs` and `link` members, and the Spring Boot version the build resolved,
 * which `generate` checks against the compatibility matrix. The IR passed beside it is already the entry's view.
 */
public data class SpringBootEntry(
    val id: String,
    val options: JsonObject,
    val springBootVersion: String,
    val artefacts: JsonObject = JsonObject(emptyMap()),
    val frameworkDocs: String? = null,
    val link: Map<String, String> = emptyMap(),
    val frameworkRoutes: List<FrameworkRoute> = emptyList(),
)

/** One framework route the boot check accepts outside the contract (ADR 0011 `frameworkRoutes`, FR-25). */
public data class FrameworkRoute(val path: String, val reason: String, val method: String? = null) {
    internal fun toJson(): JsonObject = JsonObject(
        buildMap {
            put("path", JsonPrimitive(path))
            put("reason", JsonPrimitive(reason))
            method?.let { put("method", JsonPrimitive(it.uppercase(java.util.Locale.ROOT))) }
        },
    )
}

private const val SUPPORTED_SPRING_BOOT_MAJOR = 4
private const val BOOT_CHECK = "bootCheck"
private const val NATIVE_DOCS = "nativeDocs"
private const val ACCESS_HOOKS = "accessHooks"

/** The entry members this release cannot serve, each refused by name with the release that brings it. */
internal fun checkEntry(entry: SpringBootEntry, options: SpringBootOptions, refusals: MutableList<SpringBootRefusal>) {
    checkSpringBootVersion(entry.springBootVersion, refusals)

    for ((kind, provider) in entry.link) {
        refusals += SpringBootRefusal(
            code = "link.kind.not-consumed",
            message = "The entry '${entry.id}' links '$kind' to '$provider', but the spring-boot target consumes no link: it generates its own types and validators.",
            fix = "Remove the '$kind' link from the entry '${entry.id}'.",
            member = IrPlace.ROOT.below("link", kind).member,
        )
    }

    for ((artefact, value) in entry.artefacts) checkArtefact(artefact, value, refusals)


}

private fun checkSpringBootVersion(version: String, refusals: MutableList<SpringBootRefusal>) {
    val major = version.substringBefore('.').toIntOrNull()
    if (major == SUPPORTED_SPRING_BOOT_MAJOR) return

    refusals += SpringBootRefusal(
        code = "framework.version.unsupported",
        message = "The build resolves Spring Boot '$version'; the spring-boot target supports Spring Boot $SUPPORTED_SPRING_BOOT_MAJOR.x only (Spring Framework 7, Jackson 3), and 3.x is incompatible.",
        fix = "Upgrade the app to Spring Boot $SUPPORTED_SPRING_BOOT_MAJOR.x.",
        member = "/springBootVersion",
    )
}

private fun checkArtefact(artefact: String, value: JsonElement, refusals: MutableList<SpringBootRefusal>) {
    val member = "/artefacts/$artefact"

    when (artefact) {
        // Its value is validated by the app config schema; the boot check reads it from the contract table.
        BOOT_CHECK -> if ((value as? JsonObject)?.get("hooks") == JsonPrimitive("warn")) {
            refusals += waitingEntryMember("artefact.bootCheck.hooks.warn", "$member/hooks", "'bootCheck.hooks: warn' (start with hooks missing)", Delivery.CONSUMER)
        }
        // Its value is validated by the app config schema; `NativeDocs.of` reads it.
        NATIVE_DOCS -> Unit
        ACCESS_HOOKS -> if (value == JsonPrimitive(false)) {
            refusals += waitingEntryMember("artefact.accessHooks", member, "'accessHooks: false' (native access)", Delivery.CONSUMER)
        }
        else -> refusals += SpringBootRefusal(
            code = "artefact.unknown",
            message = "The artefact '$artefact' is not one the spring-boot target emits; it takes '$BOOT_CHECK', '$NATIVE_DOCS' and '$ACCESS_HOOKS'.",
            fix = "Remove '$artefact' from the entry's `artefacts`.",
            member = member,
        )
    }
}

private fun waitingEntryMember(form: String, member: String, description: String, delivery: Delivery): SpringBootRefusal =
    SpringBootRefusal(
        code = "$form.unsupported",
        message = "$description is not generated by the spring-boot target yet: ${delivery.description}.",
        fix = "Remove it from the target entry, or update the target to a release that generates it.",
        member = member,
    )
