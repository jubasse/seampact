"""A page fact 1.0 does not generate is refused by name: the reference's changes feed, whose page carries
`complete`."""

from pathlib import Path

import pytest

from seampact.fastapi.generator import FastApiGenerator
from seampact.ir.read import read_ir
from seampact.ir.run.generator import GenerationRefusedError

from .test_golden import reference_entry

_PAGING_IR = "fixtures/golden/reference/tasksPaging.ir.json"
_REFUSED_FACT = "paging.handlerResult.unsupported"


def test_the_complete_page_fact_of_a_changes_feed_is_refused_by_name(repository_root: Path) -> None:
    generator = FastApiGenerator()
    ir = read_ir((repository_root / _PAGING_IR).read_text(encoding="utf-8"), generator.ir_support())

    with pytest.raises(GenerationRefusedError) as refused:
        generator.generate(ir, reference_entry("tasksPaging"))

    refused_facts = [problem.message for problem in refused.value.problems if problem.code == _REFUSED_FACT]

    assert len(refused_facts) == 2
    assert "The page fact 'complete' is not generated by the fastapi target yet" in refused_facts[0]
